def run_tstream(w: Writer, inputs: Sequence[Row]) -> None:
    theme = X.theme_of(inputs)
    policy = CommitPolicy[one(inputs, "policy")[1].upper()]
    found = one(inputs, "width")
    width = sp_from_px(fl(found[2]), theme.px_per_inch)
    chunks = [unq(r[1]) for r in rows_of(inputs, "chunk")]

    capture = X.Capture()
    with capture.installed():
        stream = StreamDocument(theme, fontlib_metrics, policy=policy, math=markdown_math())
        view = StreamView(stream, MEASURE)
        runs = RunIndex(capture)
        was_blocks: tuple[Any, ...] = ()
        was_cells: dict[tuple[int, int, int], list[str]] = {}
        was_units: dict[int, tuple[Any, ...]] = {}
        was_columns: dict[int, tuple[int, ...]] = {}
        totals = {"steps": 0, "built": 0, "moved": 0}

        def step(number: int, label: str) -> None:
            nonlocal was_blocks, was_cells, was_units, was_columns
            view.sync()
            layout = view.layout_for(width)
            blocks = stream.blocks
            committed = len(stream.committed)
            w.r("step", number, label, stream.revision, committed, len(stream.live), len(layout.placed),
                layout.height, layout.length)  # fmt: skip
            now_cells: dict[tuple[int, int, int], list[str]] = {}
            for index, block in enumerate(blocks):
                state = "committed" if index < committed else "live"
                if isinstance(block, TableBlock):
                    rows = ui._table_rows(block)
                    # `stable` carries one cell count for the table and none
                    # per row: the converter gives every row the header's.
                    assert len({len(cells_) for cells_ in rows}) <= 1, "no row of a table in a stream is ragged"
                    changed: list[str] = []
                    for r, cells_ in enumerate(rows):
                        for c, cell in enumerate(cells_):
                            made = cell_rows(index, r, c, cell, runs.content(cell))
                            now_cells[(index, r, c)] = made
                            if was_cells.get((index, r, c)) != made:
                                changed += made
                    if changed or not (index < len(was_blocks) and was_blocks[index] is block):
                        w.r("stable", index, state, max((len(cells_) for cells_ in rows), default=0),
                            len(rows), bool(block.header), block.left_indent, len(block.aligns), *block.aligns)  # fmt: skip
                        w.lines += changed
                elif not (index < len(was_blocks) and was_blocks[index] is block):
                    w.lines.append(" ".join(X.block_row(index, state, block)))

            # The widths each table was set to, read off its cell boxes, and
            # what the view holds for it.
            tm = table_map(layout, view._layout_blocks(width), {}, _NoCells())
            columns: dict[int, tuple[int, ...]] = {}
            for index in sorted(tm.tables):
                geom = tm.tables[index]
                set_to = geom.columns or ()
                columns[index] = set_to
                held = view._held.get(index)
                kept = view._kept.get(index)
                mode = "held" if held is not None else "kept" if kept is not None else "plain"
                stated = held if held is not None else kept if kept is not None else ()
                natural = ui.table_natural_widths(blocks[index], view.theme, MEASURE)
                before = was_columns.get(index)
                moved = (
                    -1 if before is None or len(before) != len(set_to)
                    else sum(1 for a, b in zip(before, set_to, strict=True) if a != b)
                )  # fmt: skip
                totals["moved"] += max(moved, 0)
                w.r("ttable", index, "committed" if index < committed else "live", len(geom.rows), geom.pieces,
                    mode, moved, sum(1 for found_row in geom.rows if found_row.wrapped))  # fmt: skip
                w.r("tnatural", index, len(natural), *natural)
                w.r("tstated", index, len(stated), *stated)
                w.r("tset", index, len(set_to), *set_to)
            stats = layout.stats
            w.r("built", len(stats.built), *stats.built)
            units: dict[int, tuple[Any, ...]] = {}
            for position, unit in enumerate(layout.placed):
                units[position] = (unit.block_start, len(unit.blocks), -1 if unit.part is None else unit.part,
                                   unit.y, unit.height, unit.base, unit.unit.count, X.digest(unit.unit.cmds))  # fmt: skip
                if was_units.get(position) != units[position]:
                    w.r("unit", position, *units[position])
            w.r("endstep")
            totals["steps"] += 1
            totals["built"] += len(stats.built)
            was_blocks, was_cells, was_units, was_columns = blocks, now_cells, units, columns

        for number, chunk in enumerate(chunks):
            stream.append(chunk)
            step(number, "append")
        stream.close()
        step(len(chunks), "close")
        layout = view.layout_for(width)
        w.r("final", len(stream.blocks), layout.height, layout.length, X.digest(layout.cmds))
        w.r("totals", totals["steps"], totals["built"], totals["moved"])
        emit_cmds(w, layout.cmds)


