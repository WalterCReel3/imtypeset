#!/usr/bin/env python3
"""
Dump goldens for a TABLE AMONG OTHER BLOCKS from the Python reference
(imgui-adv-text): selection, hit testing and copy through its cells and across
the blocks around it, find hits and links in cells, and a table that grows a
row at a time.

tests/golden/tables holds a table's layout alone and tests/golden/doc drops
every table from its documents (FORMAT-doc.md §7). This is what lies between:
nothing here re-records how a table is set, and everything here needs one.

Run from the imtypeset repository root, with the reference's interpreter:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=build/advtext-reference \\
        ../imgui-adv-text/.venv/bin/python -P -B tools/oracle/dump_doc_tables.py

    ... dump_doc_tables.py --check   dump again in memory and compare with the
                                     files, byte for byte; writes nothing

Writes tests/golden/doc-tables/*.golden. The record vocabulary is
tools/oracle/FORMAT-doc-tables.md, over FORMAT-doc.md's.

Nothing is written into the reference: Python is run with -B, and the
reference is only imported and called.

Golden files
------------
  selection.golden   kind `tdoc`: documents with tables at several widths --
                     every reading-order index as (block, row, column, byte),
                     each row's and cell's index range and rectangles, the
                     separators of a copy, and drags, probes and ranges
                     through cells and across the table's edges; find hits
                     and links in cells
  stream.golden      kind `tstream`: a table arriving in chunks -- per step
                     the widths each live column is held at and the widths
                     the table was set to, the pieces a long table is laid
                     out in, and which units were built

What the script asserts while it dumps (a failure writes nothing): every index
a table owns lies in exactly one cell and every cell box owns at least one;
no index of a cell with no material has a byte; `map_table` puts each cell's
material in that cell's range; a table that is not sized by the view is set to
`table_columns`; every row of a table in a stream has as many cells as the
table has columns; a colour span set on a table changes nothing that is drawn.

Which fields are the reference's own return values and which this script
works out from them is FORMAT-doc-tables.md §0. A caret's position is the
second kind.

Every group is dumped in memory and every `advtext` module then loaded is
checked against the pinned tree before the first file is written.
"""

