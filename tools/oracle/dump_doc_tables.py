@dataclass(slots=True)
class RunIndex:
    """
    The converter's runs by the identity of their first node. A cell's
    material is `tuple(run.nodes)`: the same node objects.
    """

    capture: X.Capture
    seen: int = 0
    by_first: dict[int, Any] = field(default_factory=dict)

    def content(self, cell: markdown.TableCell) -> X.Content:
        if not cell.material:
            return X.Content("", {}, [])
        for run in self.capture.pinned[self.seen :]:
            if run.nodes:
                self.by_first[id(run.nodes[0])] = run
        self.seen = len(self.capture.pinned)
        run = self.by_first[id(cell.material[0])]
        assert len(run.nodes) == len(cell.material)
        assert all(a is b for a, b in zip(run.nodes, cell.material, strict=True))
        shim = types.SimpleNamespace(
            material=cell.material, style=types.SimpleNamespace(first_line_indent=0)
        )
        return X.text_content(shim, self.capture.by_run[id(run)])  # type: ignore[arg-type]


CellContents = dict[tuple[int, int, int], X.Content]  # (block, row, column) -> its text


def cell_contents(blocks: Sequence[Any], runs: RunIndex) -> CellContents:
    out: CellContents = {}
    for number, block in enumerate(blocks):
        if isinstance(block, TableBlock):
            for r, cells in enumerate(ui._table_rows(block)):
                for c, cell in enumerate(cells):
                    out[(number, r, c)] = runs.content(cell)
    return out


def cell_rows(number: int, r: int, c: int, cell: markdown.TableCell, content: X.Content) -> list[str]:
    w = Writer("", "")
    w.lines = []
    w.r("cell", number, r, c, cell.header, len(cell.links), len(cell.formulas))
    w.r("content", len(content.text.encode("utf-8")), len(cell.material), q(content.text))
    X.emit_pieces(w, content)
    X.emit_spans(w, content, cell.links, cell.formulas)
    w.r("endcell")
    return w.lines


def emit_table(w: Writer, doc: X.Doc, cells: CellContents, number: int, block: TableBlock) -> None:
    theme = doc.theme
    style = block.style
    rows = ui._table_rows(block)
    depth = U._list_depth(block, 0, theme.list_indent, theme.quote_indent)
    w.r("table", number, max((len(cells_) for cells_ in rows), default=0), len(rows), bool(block.header),
        q(style.font.key), block.left_indent, style.space_above, style.space_below)  # fmt: skip
    blk.emit_style(w, style)
    w.r("nest", -1 if depth is None else depth)
    w.r("aligns", len(block.aligns), *block.aligns)
    for r, cells_ in enumerate(rows):
        w.r("row", r, len(cells_))
        for c, cell in enumerate(cells_):
            w.lines += cell_rows(number, r, c, cell, cells[(number, r, c)])
    w.r("endtable")


def emit_tblocks(w: Writer, doc: X.Doc, cells: CellContents) -> None:
    X.emit_theme(w, doc)
    w.r("tabledecor", doc.theme.cell_padding)
    blocks = doc.document.blocks
    w.r("blocks", len(blocks))
    for number, block in enumerate(blocks):
        if isinstance(block, TableBlock):
            emit_table(w, doc, cells, number, block)
        else:
            X.emit_block(w, doc, number, block)
    w.r("endblocks")


