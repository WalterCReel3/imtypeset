def table_queries(layout: U.UnitLayout, tm: TMap) -> dict[str, list[tuple[Any, ...]]]:
    model = layout.model
    length = layout.length
    ranges: list[tuple[int, int]] = []
    drags: list[tuple[Any, ...]] = []
    probes: list[tuple[int, int]] = []

    def clip(index: int) -> int:
        return min(max(index, 0), length)

    for number in sorted(tm.tables):
        geom = tm.tables[number]
        flat = [(found.row, c, start, end) for found in geom.rows for c, start, end in found.cells]
        if not flat:
            continue
        first, last = flat[0][2], flat[-1][3]
        ranges += [(first, last), (clip(first - 3), (flat[0][2] + flat[0][3]) // 2),
                   ((flat[-1][2] + flat[-1][3]) // 2, clip(last + 3)), (clip(first - 3), clip(last + 3)),
                   (clip(first - 1), first), (last, clip(last + 1))]  # fmt: skip
        for _, _, start, end in flat:
            ranges += [(start, end), (start, start)]
        for (_, _, a0, a1), (_, _, b0, b1) in zip(flat, flat[1:], strict=False):
            ranges += [((a0 + a1) // 2, (b0 + b1) // 2), (clip(a1 - 1), clip(b0 + 1)), (a0, b0), (a1, b1)]
        for found in geom.rows:
            ranges.append((found.start, found.end))
        for upper, lower in zip(geom.rows, geom.rows[1:], strict=False):
            ranges.append(((upper.start + upper.end) // 2, (lower.start + lower.end) // 2))
            for (c, a0, a1), (_, b0, b1) in zip(upper.cells, lower.cells, strict=False):
                if c:
                    ranges.append(((a0 + a1) // 2, (b0 + b1) // 2))  # down a column: reads row-major

        centre: dict[tuple[int, int], list[tuple[int, int]]] = {}
        for r, c, start, end in flat:
            found_rects = model.rects(Selection(start, end))
            centre[(r, c)] = [(rect.x + rect.width // 2, rect.y + rect.height // 2) for rect in found_rects]
        for (r, c), points in sorted(centre.items()):
            probes += points[:1] + points[-1:]
            here = points[:1]
            right = centre.get((r, c + 1), [])[:1]
            below = centre.get((r + 1, c), [])[-1:]
            for granularity in X.GRANULARITIES:
                for other in (right, below):
                    if here and other:
                        drags.append((*here[0], *other[0], granularity))
                        drags.append((*other[0], *here[0], granularity))
        corners = (centre[flat[0][:2]][:1], centre[flat[-1][:2]][-1:])
        if corners[0] and corners[1]:
            for granularity in X.GRANULARITIES:
                drags.append((*corners[0][0], *corners[1][0], granularity))

        edges = [geom.left]
        for column in geom.columns or ():
            edges.append(edges[-1] + column)
        pixel = sp_from_px(1.0, 96.0)
        for found in geom.rows:
            line = found.line
            assert line is not None
            top, bottom = line.y - line.height, line.y + line.depth
            middle = (top + bottom) // 2
            for edge in edges:
                probes += [(edge - pixel, middle), (edge, middle), (edge + pixel, middle)]
            probes += [(edges[0] - 1000 * pixel, middle), (edges[-1] + 1000 * pixel, middle)]
            for x in ((edges[0] + edges[1]) // 2, (edges[-2] + edges[-1]) // 2):
                probes += [(x, top - 1), (x, top), (x, bottom - 1), (x, bottom)]
    return {"range": ranges, "drag": drags, "probe": probes}


def emit_range(w: Writer, view: bv.BareView, layout: U.UnitLayout, tm: TMap, start: int, end: int) -> None:
    selection = Selection(start, end)
    view.select(selection)
    touched = view.selected_blocks()
    w.r("range", start, end, *tm.span(start, end), len(touched), *touched)
    w.r("copy", q(layout.model.copy_text(selection)))
    found = layout.model.rects(selection)
    w.r("rects", len(found))
    for rect in found:
        w.r("rect", rect.x, rect.y, rect.width, rect.height)
    view.clear_selection()


MARK = rgba(0xFF, 0xE0, 0x66, 0x99)


def emit_decorations(w: Writer, doc: X.Doc, cells: CellContents, view: bv.BareView, layout: U.UnitLayout,
                     tm: TMap, needles: Sequence[tuple[str, bool]]) -> None:  # fmt: skip
    blocks = doc.document.blocks
    index = spans.FindIndex.of(blocks)
    w.r("founds", len(needles))
    for needle, fold in needles:
        matches = index.find(needle, ignore_case=fold)
        w.r("found", q(needle), fold, len(matches))
        for match in matches:
            rects = view.span_rects(match.block, match.start, match.end, cell=match.cell)
            if match.cell is None:
                r, c = -1, -1
                b0, b1 = doc.contents[match.block].span(match.start, match.end)
            else:
                r, c = match.cell
                b0, b1 = cells[(match.block, r, c)].span(match.start, match.end)
            w.r("match", match.block, r, c, match.start, match.end, b0, b1, len(rects))
            for rect in rects:
                w.r("rect", rect.x, rect.y, rect.width, rect.height)

    palette = Palette()
    visible = list(layout.visible_units(X.EVERYWHERE))
    inks, fills = view._decorate(visible, palette)
    links = tuple(view._links)
    # A colour span on a table is kept and not applied: the reference has no
    # coordinates for one across cells, so a find hit in a cell cannot be
    # marked through `set_colours`. Asserted, so that the absence is a fact.
    for number in tm.tables:
        view.set_colours(number, (spans.ColourSpan(0, 4, mark=MARK),))
    again = view._decorate(visible, palette)
    assert again == (inks, fills), "a colour span on a table draws nothing"
    view.clear_colours()

    w.r("unmapped_blocks", view._unmapped)
    w.r("decoinks", len(inks))
    for start, end, colour in inks:
        w.r("ink", start, end, colour, *tm.span(start, end))
    w.r("fills", len(fills))
    for rect, colour in fills:
        w.r("fill", rect.x, rect.y, rect.width, rect.height, colour)
    w.r("linkareas", len(links))
    for area in links:
        r, c = tm.cell_of.get(area.runs[0].start, (-1, -1)) if area.runs else (-1, -1)
        w.r("linkarea", area.block, area.number, r, c, q(area.target), len(area.runs), len(area.rects))
        for run in area.runs:
            w.r("lrun", run.line, run.start, run.end, *tm.span(run.start, run.end))
        for rect in area.rects:
            w.r("rect", rect.x, rect.y, rect.width, rect.height)


def without_headers(doc: X.Doc) -> X.Doc:
    """
    `doc` with the header row of every table taken away: the rows that were
    its body are the whole table. Markdown cannot write a table without a
    header and a host that builds its blocks can, so the document is built
    from markdown and the block changed in memory, before anything is laid
    out. Block numbers, and so `doc.contents`, are as they were.
    """
    blocks = tuple(
        dataclasses.replace(block, header=()) if isinstance(block, TableBlock) else block
        for block in doc.document.blocks
    )
    assert any(isinstance(block, TableBlock) and block.rows for block in blocks)
    return X.Doc(doc.theme, dataclasses.replace(doc.document, blocks=blocks), doc.capture, doc.contents)


def run_tdoc(w: Writer, inputs: Sequence[Row]) -> None:
    doc = X.build_doc(inputs)
    if rows_of(inputs, "dropheader"):
        doc = without_headers(doc)
    cells = cell_contents(doc.document.blocks, RunIndex(doc.capture))
    emit_tblocks(w, doc, cells)
    seed = int(one(inputs, "seed")[1])
    styled = one(inputs, "links")[1] == "1"
    needles = [(unq(r[2]), r[1] == "1") for r in rows_of(inputs, "needle")]
    nblocks = len(doc.document.blocks)
    for number, found in enumerate(rows_of(inputs, "width")):
        name = unq(found[1])
        width = sp_from_px(fl(found[2]), doc.theme.px_per_inch)
        view = bv.BareView(document=doc.document, theme=doc.theme, measure=MEASURE, style_links=styled)
        layout = view.layout_for(width)
        model = layout.model
        tm = table_map(layout, doc.document.blocks, doc.contents, cells)
        w.r("layout", q(name), width)
        X.emit_units(w, view, layout)
        X.emit_leads(w, layout)
        emit_cmds(w, layout.cmds)
        emit_tmap(w, view, layout, tm)
        emit_geometry(w, doc, layout, tm)
        emit_copy_maps(w, layout, tm)

        general = X.choose_queries(layout, nblocks, seed + number)
        through = table_queries(layout, tm)
        drags = X.thinned(through["drag"], 150) + X.thinned(general["drag"], 60)
        probes = X.thinned(through["probe"], 220) + X.thinned(general["probe"], 40)
        ranges = X.thinned(through["range"], 220) + X.thinned(general["range"], 60)
        w.r("drags", len(drags))
        for ax, ay, bx, by, granularity in drags:
            chosen = model.select_at(Point(ax, ay), Point(bx, by), granularity)
            w.r("drag", ax, ay, bx, by, granularity, chosen.start, chosen.end, *tm.span(chosen.start, chosen.end))
        w.r("probes", len(probes))
        for x, y in probes:
            point = Point(x, y)
            hit = model.hit(point)
            under = layout.block_at(point)
            word, line = model.word_at(point), model.line_at(point)
            w.r("probe", x, y, hit, -1 if under is None else under, *tm.pos(hit),
                word.start, word.end, line.start, line.end)  # fmt: skip
        w.r("ranges", len(ranges))
        for start, end in ranges:
            emit_range(w, view, layout, tm, start, end)
        w.r("blocktexts", nblocks)
        for block in range(nblocks):
            w.r("blocktext", block, q(view.block_text(block)))
        emit_decorations(w, doc, cells, view, layout, tm, needles)
        w.r("endlayout")


