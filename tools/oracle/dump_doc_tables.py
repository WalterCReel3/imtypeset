RUNNERS = {"tdoc": run_tdoc, "tstream": run_tstream}

GROUPS: dict[str, tuple[str, Any]] = {
    "selection": (
        """
A table among other blocks: every reading-order index as (block, row, column,
byte), each row's and cell's index range and rectangles, what a copy writes
between cells and rows, drags, probes and ranges through cells and across the
table's edges, and find hits and links in cells.
""",
        selection_cases,
    ),
    "stream": (
        """
A table arriving in chunks: after each chunk its cells, the widths each column
is held at, the widths the table was set to and how many of them moved, the
pieces it is laid out in, and the units the reference built.
""",
        stream_cases,
    ),
}


def dump(group: str) -> Writer:
    about, cases = GROUPS[group]
    w = Writer(group, about)
    for name, kind, inputs in cases():
        w.case(name, kind)
        w.lines += [" ".join(r) for r in inputs]
        w.r("expect")
        RUNNERS[kind](w, inputs)
        w.end()
    return w


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").strip().split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="dump in memory and compare with the files")
    parser.add_argument("--only", default="", help="comma-separated groups: " + ", ".join(GROUPS))
    args = parser.parse_args()
    chosen = [name for name in GROUPS if not args.only or name in args.only.split(",")]
    assert chosen, "no such group"
    dumped = [(name, dump(name)) for name in chosen]
    # After the last import a dump makes and before the first byte is written.
    pinned_reference.require_all_modules()
    if not args.check:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
    status = 0
    for name, w in dumped:
        text = w.text()
        path = OUT_DIR / f"{name}.golden"
        if args.check:
            same = path.is_file() and path.read_text(encoding="utf-8") == text
            print(f"{name}.golden: {w.cases} cases, {'identical' if same else 'DIFFERS from the file'}")
            status |= 0 if same else 1
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"{name}.golden: {w.cases} cases, {len(w.lines)} lines, {len(text.encode('utf-8'))} bytes")
    return status


if __name__ == "__main__":
    sys.exit(main())
