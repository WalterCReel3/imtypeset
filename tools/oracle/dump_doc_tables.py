# Positions: every index as (block, row, column, byte)
# --------------------------------------------------------------------------


@dataclass(slots=True)
class RowGeom:
    row: int
    start: int
    end: int
    wrapped: bool
    cells: list[tuple[int, int, int]]  # (column, index_start, index_end)
    line: Line | None = None


@dataclass(slots=True)
class TableGeom:
    block: int
    left: int = 0
    columns: tuple[int, ...] | None = None
    rows: list[RowGeom] = field(default_factory=list)
    pieces: int = 0


@dataclass(slots=True)
class TMap:
    base: X.IndexMap
    cell_of: dict[int, tuple[int, int]]
    tables: dict[int, TableGeom]

    def pos(self, index: int) -> tuple[int, int, int, int]:
        block, byte = self.base.pos(index)
        r, c = self.cell_of.get(index, (-1, -1))
        return (block, r, c, byte)

    def span(self, start: int, end: int) -> tuple[int, ...]:
        """
        `[start, end)` as the position of its first sourced item and the
        position, byte END exclusive, of its last; eight -1 when it holds none.
        """
        where = self.base.where
        low, high = max(start, 0), min(end, len(self.base.owner))
        first = next((i for i in range(low, high) if i in where), None)
        if first is None:
            return (-1,) * 8
        last = next(i for i in range(high - 1, low - 1, -1) if i in where)
        a, b = self.pos(first), self.pos(last)
        return (*a, b[0], b[1], b[2], sum(where[last]))


def _boxes(node: Box) -> list[Box]:
    return [child for child in node.contents if isinstance(child, Box)]


def table_map(layout: U.UnitLayout, doc_blocks: Sequence[Any], contents: dict[int, X.Content],
              cells: CellContents) -> TMap:  # fmt: skip
    base = X.index_map(layout, contents)
    cell_of: dict[int, tuple[int, int]] = {}
    tables: dict[int, TableGeom] = {}
    for unit in layout.placed:
        for number, piece in zip(unit.block_range, unit.blocks, strict=True):
            if not isinstance(piece, TableBlock):
                continue
            geom = tables.setdefault(number, TableGeom(number))
            geom.pieces += 1
            rows_before = len(geom.rows)
            own = unit.indices_of(number)
            rows = ui._table_rows(piece)
            # A row box holds a box per cell; the rule under the header holds none.
            row_boxes = [node for node in _boxes(unit.unit.box) if _boxes(node)]
            assert len(row_boxes) == len(rows)
            whole = ui._table_rows(doc_blocks[number])
            lines = [cmd for cmd in unit.cmds if isinstance(cmd, Line)]
            cursor = own.start
            identity: dict[int, tuple[int, int]] = {}
            for local, (cells_, row_box) in enumerate(zip(rows, row_boxes, strict=True)):
                r = rows_before + local
                cell_boxes = _boxes(row_box)
                widths = tuple(box.width for box in cell_boxes)
                assert geom.columns in (None, widths), "every row is set to the same columns"
                geom.columns = widths
                start = cursor
                held: list[tuple[int, int, int]] = []
                for c, cell_box in enumerate(cell_boxes):
                    count = spans.index_count(cell_box)
                    assert count >= 1, "a cell box owns an index even when the cell is empty"
                    for index in range(cursor, cursor + count):
                        assert base.owner[index] == number and index not in cell_of
                        cell_of[index] = (r, c)
                    held.append((c, cursor, cursor + count))
                    cursor += count
                    if c < len(cells_):
                        identity[id(cells_[c])] = (r, c)
                        assert cells_[c].material == whole[r][c].material
                # The row's own Line comes before the lines of its cells.
                outer = next(cmd for cmd in lines if (cmd.start, cmd.end) == (start, cursor))
                # The row box begins with a kern of the table's indent.
                geom.left = outer.x + piece.left_indent
                assert outer.width == piece.left_indent + sum(widths)
                geom.rows.append(
                    RowGeom(r, start, cursor, any(box.kind is BoxKind.VLIST for box in cell_boxes), held, outer)
                )
            assert cursor == own.stop, "a table's indices are its cells' and nothing else's"
            for cell, mapped in spans.map_table(piece, unit.unit.box, base=own.start):
                r, c = identity[id(cell)]
                content = cells[(number, r, c)]
                for material_index, local_index in enumerate(mapped.shipped):
                    found = content.byte_of.get(material_index)
                    if local_index is None or found is None:
                        continue
                    for k in range(mapped.extent[material_index]):
                        index = mapped.base + local_index + k
                        assert cell_of[index] == (r, c), "map_table and the cell boxes agree"
                        base.where[index] = found
            for found_row in geom.rows[rows_before:]:
                for c, low, high in found_row.cells:
                    cells_ = whole[found_row.row]
                    if c >= len(cells_) or not cells_[c].material:
                        assert not any(index in base.where for index in range(low, high)), (
                            "no index of a cell with no material has a byte"
                        )
    return TMap(base, cell_of, tables)


def emit_tmap(w: Writer, view: bv.BareView, layout: U.UnitLayout, tm: TMap) -> None:
    for number in range(len(view.document.blocks)):
        own = layout.indices_of_block(number)
        tokens: list[object] = []
        if number in tm.tables:
            for index in own:
                found = tm.base.where.get(index)
                tokens += [*tm.cell_of[index], *((-1, 0) if found is None else found)]
            w.r("tmap", number, own.start, len(own), *tokens)
        else:
            for index in own:
                found = tm.base.where.get(index)
                tokens += [-1, 0] if found is None else [found[0], found[1]]
            w.r("imap", number, own.start, len(own), *tokens)
    w.r("unmapped", len(tm.base.unmapped), *tm.base.unmapped)


def emit_geometry(w: Writer, doc: X.Doc, layout: U.UnitLayout, tm: TMap, *, sized: bool = False) -> None:
    model = layout.model
    w.r("tables", len(tm.tables))
    for number in sorted(tm.tables):
        geom = tm.tables[number]
        columns = geom.columns or ()
        if not sized:
            block = doc.document.blocks[number]
            assert columns == ui.table_columns(block, doc.theme, layout.width, MEASURE, PARAMS)
        w.r("tgeom", number, geom.left, len(geom.rows), len(columns), *columns)
        for found in geom.rows:
            line = found.line
            assert line is not None
            w.r("trow", number, found.row, found.start, found.end, found.wrapped,
                line.y - line.height, line.height + line.depth, len(found.cells))  # fmt: skip
            for c, start, end in found.cells:
                rects = model.rects(Selection(start, end))
                w.r("tcell", number, found.row, c, start, end, len(rects))
                for rect in rects:
                    w.r("rect", rect.x, rect.y, rect.width, rect.height)


def emit_copy_maps(w: Writer, layout: U.UnitLayout, tm: TMap) -> None:
    model = layout.model
    for tag, found in (
        ("sep", model.separators_within(0, layout.length)),
        ("atomtext", model.atoms_within(0, layout.length)),
        ("original", model.originals_within(0, layout.length)),
    ):
        w.r(tag + "s", len(found))
        for index in sorted(found):
            w.r(tag, index, *tm.pos(index), q(found[index]))


