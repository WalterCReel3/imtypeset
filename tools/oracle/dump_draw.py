def emit_case(w: Writer, setup: Setup, case: Case) -> dict[str, int]:
    ran = run_case(setup, case)
    ops = pair_text_ops(case, ran)
    tally = check_geometry(case, ran, ops)
    replayed, replayed_stats = replay(case, ran)
    assert replayed == [o[:-2] for o in ops], (case.name, next(
        (a, b) for a, b in zip(replayed + [None], [o[:-2] for o in ops] + [None]) if a != b))  # fmt: skip
    assert replayed_stats == (ran.stats.glyphs, ran.stats.missing, ran.stats.rules), case.name
    text_no_pixel_snap = int(imgui.ImDrawListFlags_.text_no_pixel_snap)
    assert ran.flag_writes == [ran.list_flags | text_no_pixel_snap, ran.list_flags], case.name

    w.case(case.name, "draw")
    w.r("note", q(case.note))
    # INPUT
    w.r("fonts", case.fonts)
    w.r("origin", ran.origin[0], ran.origin[1])
    w.r("ppi", float(case.px_per_inch))
    w.r("debug", case.debug)
    w.r("clip", *ran.clip)
    w.r("listflags", ran.list_flags, text_no_pixel_snap)
    p = case.palette
    w.r("palette", p.highlight, p.rule, p.debug_box, p.debug_baseline, p.debug_stretched, p.debug_shrunk)
    w.r("keys", len(ran.keys))
    for k in ran.keys:
        w.r("key", q(k.key), q(k.role), k.size_sp, k.bound, k.m_ascent, k.m_descent, k.m_em,
            k.requested_px, k.baked_size, k.baked_ascent, k.baked_descent)  # fmt: skip
    w.r("boxes", len(ran.boxes))
    for b in ran.boxes.values():
        w.r("box", q(b.key), b.codepoint, b.in_font, b.visible, b.colored, b.x0, b.y0, b.x1, b.y1, b.advance_x)
    w.r("fills", len(case.fills))
    for rect, colour in case.fills:
        w.r("fill", rect.x, rect.y, rect.width, rect.height, colour)
    w.r("highlights", len(case.highlights))
    for rect in case.highlights:
        w.r("highlight", rect.x, rect.y, rect.width, rect.height)
    w.r("inks", len(case.inks))
    for start, end, colour in case.inks:
        w.r("ink", start, end, colour)
    w.r("runs", len(case.runs))
    for cmds, ink in case.runs:
        w.r("run", ink)
        emit_cmds(w, cmds)
    # EXPECTED
    w.r("stats", ran.stats.glyphs, ran.stats.missing, ran.stats.rules)
    w.r("ops", len(ops))
    for o in ops:
        w.r(*o)
    w.r("vtx", len(ran.vertices))
    for x, y, colour, _u, _v in ran.vertices:
        w.r("v", x, y, colour)
    assert len(ran.indices) % 3 == 0
    w.r("tris", len(ran.indices) // 3)
    for i in range(0, len(ran.indices), 3):
        w.r("tri", *ran.indices[i : i + 3])
    w.r("drawcmds", len(ran.drawcmds))
    for c in ran.drawcmds:
        w.r("drawcmd", *c)
    # Optional, and written for a few cases only: texture coordinates. They
    # depend on the order glyphs were baked in and on the atlas packer, so a
    # port's will differ; what carries over is which vertices share the white
    # pixel and that a glyph quad spans a rectangle of the atlas.
    if case.uv:
        w.r("uvs", len(ran.vertices), ran.white_uv[0], ran.white_uv[1])
        for _x, _y, _colour, u, v in ran.vertices:
            w.r("uv", u, v)
    w.end()
    # The baked ascent is a whole number of pixels for every key drawn. That is
    # what lets it cancel out of a quad's y: see FORMAT-draw.md.
    assert all(k.baked_ascent == math.floor(k.baked_ascent) for k in ran.keys), case.name
    tally["glyph_cmds"] = ran.stats.glyphs + ran.stats.missing
    tally["missing"] = ran.stats.missing
    tally["vertices"] = len(ran.vertices)
    return tally


