def shipped(
    source: str,
    width_px: float,
    *,
    px_per_inch: float = DEFAULT_PX_PER_INCH,
    align: Align = Align.JUSTIFY,
    math_inline: bool = False,
) -> tuple[DrawCmd, ...]:
    """A markdown source composed and shipped the way the reference's demo does it."""
    theme = Theme.build(px_per_inch=px_per_inch, align=align)
    measure = char_measure(fontlib_metrics)
    document = build_document(
        source, theme, fontlib_metrics, math=markdown_math() if math_inline else None
    )
    box = compose(document, theme, sp_from_px(width_px, px_per_inch), measure)
    return tuple(ship(box, Point(0, box.height), measure=measure))


def summation(size_px: float) -> tuple[DrawCmd, ...]:
    """The display-style summation with limits: the formula whose big sigma is a minted codepoint."""
    size = sp_from_px(size_px, DEFAULT_PX_PER_INCH)
    fonts = math_fonts(size, lambda at: fontlib.math_metrics(float(at)))
    nodes = mlist_to_hlist([op("∑", sup="n", sub=group("i", rel("="), "1"))], Style.DISPLAY, fonts)
    box = hpack(nodes, measure=fonts.measure).box
    return tuple(ship(box, Point(0, box.height), measure=fonts.measure))


def split_runs(cmds: tuple[DrawCmd, ...], inks: tuple[int, ...]) -> list[tuple[tuple[DrawCmd, ...], int]]:
    """The commands cut at `Line` boundaries into `len(inks)` runs of near-equal line count."""
    starts = [i for i, cmd in enumerate(cmds) if isinstance(cmd, Line)]
    if not starts or starts[0] != 0:
        starts.insert(0, 0)
    per = max(1, len(starts) // len(inks))
    cuts = [starts[i * per] for i in range(len(inks))] + [len(cmds)]
    return [(cmds[cuts[i] : cuts[i + 1]], inks[i]) for i in range(len(inks))]


def px(value: float) -> int:
    return sp_from_px(value, DEFAULT_PX_PER_INCH)


def hand_edges() -> tuple[DrawCmd, ...]:
    """Hand-built spans that reach the branches a composed document rarely does."""
    prose = font_key(Face.PROSE, px(16.0))
    bold = font_key(Face.PROSE_BOLD, px(16.0))
    big = font_key(Face.PROSE, px(27.3))
    code = font_key(Face.CODE, px(14.0))
    cmds: list[DrawCmd] = []
    index = 0

    def glyphs(key: str, codepoints: list[int], x: float, y: float, step: float = 9.37) -> float:
        nonlocal index
        for cp in codepoints:
            cmds.append(Glyph(font=key, codepoint=cp, x=px(x), y=px(y), index=index))
            index += 1
            x += step
        return x

    cmds.append(Line(x=px(0), y=px(20), width=px(300), height=px(12), depth=px(4), start=0, end=0))
    # One span: a codepoint the face lacks in the middle neither ends nor anchors it.
    x = glyphs(prose, [0x41, 0x62, 0xE000, 0x63, 0x64], 3.3, 20.0)
    # Still the same span: a space and a no-break space are glyphs with no ink,
    # U+0000 and U+000D are in Roboto's cmap and draw nothing, and the glyphs
    # after them are placed from the pen those got.
    x = glyphs(prose, [0x20, 0xA0, 0x65, 0x00, 0x0D, 0x66], x, 20.0)
    # A face change and a size change inside the span: no glue between.
    x = glyphs(bold, [0x42, 0x6F], x, 20.0)
    x = glyphs(big, [0x51, 0x67], x, 20.0, step=15.11)
    # A raised and a lowered glyph inside the span, by fractions of a pixel.
    cmds.append(Glyph(font=prose, codepoint=0x32, x=px(x), y=px(20.0 - 5.4), index=index))
    cmds.append(Glyph(font=prose, codepoint=0x69, x=px(x + 7.7), y=px(20.0 + 3.5), index=index + 1))
    index += 2
    # Glue ends the span; the next glyph anchors a new one from its own position.
    cmds.append(SetGlue(x=px(x + 14.0), y=px(20), width=px(6.2), natural=px(4.0), height=px(12), depth=px(4), index=index))
    x = glyphs(code, [0x78, 0x20, 0x20, 0x79], x + 20.2, 20.0, step=7.0)
    # An atom ends a span as glue does; so does a rule; so does a line.
    cmds.append(Atom(x=px(x), y=px(20), width=px(10), natural=px(10), height=px(12), depth=px(4), index=index))
    x = glyphs(prose, [0x54, 0x6F], x + 10.5, 20.0, step=8.1)
    cmds.append(RuleRect(x=px(x), y=px(22), width=px(12.5), height=px(1.0)))
    x = glyphs(prose, [0x54, 0x6F], x + 12.5, 20.0, step=8.1)
    cmds.append(Line(x=px(0), y=px(44.5), width=px(300), height=px(12), depth=px(4), start=index, end=index + 3))
    glyphs(prose, [0x57, 0x61, 0x2E], 0.49, 44.5, step=10.5)
    # Glue squeezed and glue at its natural width, for the debug overlay.
    cmds.append(SetGlue(x=px(40), y=px(44.5), width=px(3.1), natural=px(4.0), height=px(12), depth=px(4), index=index))
    cmds.append(SetGlue(x=px(50), y=px(44.5), width=px(4.0), natural=px(4.0), height=px(12), depth=px(4), index=index))
    return tuple(cmds)


