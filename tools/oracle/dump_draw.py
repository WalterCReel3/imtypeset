@dataclass
class Setup:
    loaded: Any  # advtext.ui.fonts.LoadedFaces
    unpatched_math: Any  # the math file as shipped, with no minted codepoints in its cmap
    loader_name: str = ""

    def fonts(self, face: Face) -> Any:
        return self.loaded(face)

    def fonts_unpatched_math(self, face: Face) -> Any:
        return self.unpatched_math if face is Face.MATH else self.loaded(face)


def make_setup() -> Setup:
    imgui.create_context()
    io = imgui.get_io()
    io.display_size = imgui.ImVec2(*DISPLAY)
    io.delta_time = 1.0 / 60.0
    io.backend_flags |= imgui.BackendFlags_.renderer_has_textures.value
    # The reference's own loader: `add_font_from_file_ttf(imgui_font_file(face),
    # DEFAULT_LOAD_PX)` on the current atlas, a default ImFontConfig, every role.
    loaded = load_faces(ALL_FACES)
    unpatched = io.fonts.add_font_from_file_ttf(str(fontlib.font_file(Face.MATH)), DEFAULT_LOAD_PX)
    setup = Setup(loaded=loaded, unpatched_math=unpatched)
    imgui.new_frame()
    setup.loader_name = str(io.fonts.font_loader_name)
    imgui.render()
    return setup


class Recorder:
    """
    A draw list that forwards every call and keeps its arguments.

    `draw_runs` reaches a draw list through `flags`, `add_text`,
    `add_rect_filled`, `add_rect` and `add_line` and nothing else.
    """

    def __init__(self, draw_list: Any) -> None:
        self._list = draw_list
        self.base = draw_list.vtx_buffer.size()
        self.ops: list[tuple[Any, ...]] = []
        self.flag_writes: list[int] = []

    @property
    def flags(self) -> int:
        return int(self._list.flags)

    @flags.setter
    def flags(self, value: int) -> None:
        self.flag_writes.append(int(value))
        self._list.flags = value

    def _note(self, kind: str, fields: tuple[Any, ...], call: Any) -> None:
        first = self._list.vtx_buffer.size()
        call()
        self.ops.append((kind, *fields, first - self.base, self._list.vtx_buffer.size() - first))

    def add_rect_filled(self, near: Any, far: Any, colour: int) -> None:
        self._note("rectfilled", (near.x, near.y, far.x, far.y, colour),
                   lambda: self._list.add_rect_filled(near, far, colour))  # fmt: skip

    def add_rect(self, near: Any, far: Any, colour: int) -> None:
        self._note("rect", (near.x, near.y, far.x, far.y, colour),
                   lambda: self._list.add_rect(near, far, colour))  # fmt: skip

    def add_line(self, start: Any, end: Any, colour: int, thickness: float) -> None:
        self._note("linesegment", (start.x, start.y, end.x, end.y, colour, float(thickness)),
                   lambda: self._list.add_line(start, end, colour, thickness))  # fmt: skip

    def add_text(self, *args: Any) -> None:
        if len(args) == 5:
            _font, size, position, colour, text = args
            fields = (float(size), position.x, position.y, colour, text)
        else:
            position, colour, text = args
            fields = (0.0, position.x, position.y, colour, text)
        self._note("text", fields, lambda: self._list.add_text(*args))


