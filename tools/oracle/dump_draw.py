    tables = dump_tables(setup)
    written.append((tables.name, tables.write()))

    w = Writer("draw.golden", "draw_runs in a headless ImGui frame: inputs, the calls it made, the vertices that resulted.")
    totals: dict[str, int] = {}
    for case in cases():
        tally = emit_case(w, setup, case)
        for key, value in tally.items():
            totals[key] = totals.get(key, 0) + value
        print(f"  {case.name}: " + " ".join(f"{k}={v}" for k, v in tally.items()))
    written.append((w.name, w.write()))

    boxes = dump_boxes(setup)
    written.append((boxes.name, boxes.write()))

    for name, size in written:
        print(f"{size:9d}  tests/golden/draw/{name}")
    print("totals: " + " ".join(f"{k}={v}" for k, v in sorted(totals.items())))
    stale = sorted(p.name for p in OUT.glob("*.golden") if p.name not in {n for n, _ in written})
    if stale:
        print("stale goldens not written by this run:", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


