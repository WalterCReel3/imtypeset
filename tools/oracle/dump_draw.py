"""
Dump draw goldens from the Python reference's ImDrawList backend.

Run from the repository root, with the reference's interpreter:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=build/advtext-reference \
        ../imgui-adv-text/.venv/bin/python -P -B tools/oracle/dump_draw.py

Writes tests/golden/draw/*.golden. Reads the reference and never writes to it.
tools/oracle/FORMAT-draw.md documents every record.

Each case runs `advtext.backends.imgui_draw.draw_runs` in a real, headless
ImGui frame and records three layers, so a port that disagrees can say where:

1. `ops`: every call the reference made on the draw list, in order, with the
   arguments it passed. This is the pen-level golden. Given the per-key
   `key` records (baked size, baked ascent) it depends on nothing a rasteriser
   produced.
2. `box` records: the glyph box ImGui reported for every (font key, codepoint)
   a case draws. This is the rasteriser's answer and nothing else.
3. `vtx`/`tri`/`drawcmd`: what ended up in the draw list. Layer 3 is layers 1
   and 2 combined by ImGui, and the script asserts the combination rule on
   every glyph and rectangle it writes (`check_geometry`).

`replay` is the pen-level rule written out again from FORMAT-draw.md, using
nothing of the reference: it recomputes every op of every case from the INPUT
records and the script fails if one differs. It is the check that the document
is sufficient, and it is the arithmetic the port has to have.

The output is a function of the reference, the font files, imgui-bundle's ImGui
and its FreeType. Running it twice writes the same bytes.
"""

