ADV: Scaled = 10
HEIGHT: Scaled = 8
DEPTH: Scaled = 2
LEADING: Scaled = 20


def text_line(text: str, *, start: int = 0, x: Scaled = 0, y: Scaled = HEIGHT, width: Scaled | None = None, adv: Scaled = ADV) -> list[DrawCmd]:
    """
    A visual line of `text`, one cell per character, spaces as glue.
    """
    cmds: list[DrawCmd] = []
    pen = x
    for offset, character in enumerate(text):
        if character == " ":
            cmds.append(SetGlue(x=pen, y=y, width=adv, natural=adv, height=HEIGHT, depth=DEPTH, index=start + offset))
        else:
            cmds.append(Glyph(font=FONT, codepoint=ord(character), x=pen, y=y, index=start + offset))
        pen += adv
    header = Line(x=x, y=y, width=pen - x if width is None else width, height=HEIGHT, depth=DEPTH, start=start, end=start + len(text))
    return [header, *cmds]


def stacked(*texts: str, x: Scaled = 0, y: Scaled = HEIGHT, leading: Scaled = LEADING) -> list[DrawCmd]:
    cmds: list[DrawCmd] = []
    start = 0
    for row, text in enumerate(texts):
        cmds.extend(text_line(text, start=start, x=x, y=y + row * leading))
        start += len(text)
    return cmds


def fill(index: int, x: Scaled, *, width: Scaled = 0, y: Scaled = HEIGHT) -> SetGlue:
    return SetGlue(x=x, y=y, width=width, natural=0, height=HEIGHT, depth=DEPTH, index=index)


def cells(*texts: str, y: Scaled = HEIGHT, start: int = 0) -> list[DrawCmd]:
    """
    One line holding several cells, each `fill text fill`: an unwrapped table row.
    """
    cmds: list[DrawCmd] = []
    index, pen = start, 0
    for text in texts:
        cmds.append(fill(index, pen, y=y))
        index += 1
        for character in text:
            cmds.append(Glyph(font=FONT, codepoint=ord(character), x=pen, y=y, index=index))
            index += 1
            pen += ADV
        cmds.append(fill(index, pen, width=3 * ADV, y=y))
        index += 1
        pen += 3 * ADV
    header = Line(x=0, y=y, width=pen, height=HEIGHT, depth=DEPTH, start=start, end=index)
    return [header, *cmds]


def side_by_side() -> list[DrawCmd]:
    """
    A wrapped table row: a container line, then a stack of lines for each cell.
    """
    row = Line(x=0, y=HEIGHT, width=200, height=HEIGHT, depth=DEPTH + 2 * LEADING, start=0, end=8)
    left = text_line("ab", start=0, x=0, y=HEIGHT)
    right = [cmd for number, text in enumerate(("cd", "ef", "gh")) for cmd in text_line(text, start=2 + 2 * number, x=100, y=HEIGHT + number * LEADING)]
    below = text_line("zz", start=8, x=0, y=HEIGHT + 4 * LEADING, width=200)
    return [row, *left, *right, *below]


