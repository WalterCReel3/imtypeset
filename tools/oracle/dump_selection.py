    out.append(("container-of-containers", [Line(0, 30, 100, 30, 30, 0, 4), Line(0, 30, 50, 30, 30, 0, 2), *text_line("ab", y=20), Line(50, 30, 50, 30, 30, 2, 4), *text_line("cd", start=2, x=50, y=40)]))

    # Atoms: a formula is one item, its glyphs repeat its index and are not items.
