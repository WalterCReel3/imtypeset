def shipped() -> list[tuple[str, list[DrawCmd], int]]:
    out: list[tuple[str, list[DrawCmd], int]] = []
    measure = char_measure(fontlib_metrics)

    for align in (Align.JUSTIFY, Align.LEFT, Align.RIGHT, Align.CENTER):
        theme = Theme.build(align=align)
        document = markdown.build_document(PROSE, theme, fontlib_metrics)
        for width in (140.0, 300.0):
            box = ui.compose(document, theme, sp_from_px(width), measure)
            cmds = ship(box, Point(0, box.height), measure=measure)
            out.append((f"prose/{align.name.lower()}/{width:g}px", cmds, 160))

    theme = Theme.build()
    document = markdown.build_document(MIXED, theme, fontlib_metrics, math=markdown_math())
    for width in (220.0, 420.0):
        box = ui.compose(document, theme, sp_from_px(width), measure)
        out.append((f"document/{width:g}px", ship(box, Point(0, box.height), measure=measure), 420))
    # The same page somewhere else: nothing depends on where the origin is.
    box = ui.compose(document, theme, sp_from_px(300.0), measure)
    out.append(("document/300px-offset", ship(box, Point(-1234567, 7654321), measure=measure), 420))

    # A formula shipped as a block of its own: stacked limits are lines inside
    # a line, and the outer line's own items then have a hole.
    fonts = formula_fonts(sp_from_px(20.0))
    for number, (source, display) in enumerate(FORMULAS):
        result = parse(source, display=display)
        assert isinstance(result, Formula)
        box = set_formula(result, fonts)
        out.append((f"formula/{number}", ship(box, Point(0, box.height), measure=fonts.measure), 260))
        assert result.style is (Style.DISPLAY if display else Style.TEXT)

    # A hand-built page through the real ship-out: a kern, a rule, a nested vbox.
    def chars(text: str) -> list[Node]:
        return [CharNode("fake@10", ord(c)) for c in text]

    space = Glue(GlueSpec(width=6 * 65536, stretch=4 * 65536, shrink=2 * 65536))
    line_one = hpack([*chars("ab"), space, *chars("cd"), Kern(-3 * 65536), *chars("e")], 80 * 65536, PackMode.EXACTLY, measure=core.fake_measure).box
    stack = vpack([hpack(chars("up"), measure=core.fake_measure).box, Rule(height=65536, depth=0), hpack(chars("down"), measure=core.fake_measure).box]).box
    line_two = hpack([*chars("x"), stack, *chars("y")], measure=core.fake_measure).box
    page = vpack([line_one, Glue(GlueSpec(width=5 * 65536)), line_two, Rule(height=2 * 65536, depth=0), hpack([], measure=core.fake_measure).box, hpack(chars("end"), measure=core.fake_measure).box]).box
    assert page.kind is BoxKind.VLIST and isinstance(page, Box)
    out.append(("hand-built-page", ship(page, Point(0, page.height), measure=core.fake_measure), 260))
    return out


