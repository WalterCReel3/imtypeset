def verify_case(records: Records) -> int:
    cmds = read_cmds(records)
    model = SelectionModel.from_commands(cmds)
    checks = 0
    row = records.take("model")
    assert (int(row[1]), int(row[2])) == (model.length, len(model.fragments))
    for fragment in model.fragments:
        row = records.take("fragment")
        assert cmds[int(row[1])] is fragment.line
        assert (int(row[2]), int(row[3])) == (fragment.start, fragment.end)
        assert (None if row[4] == "-1" else cmds[int(row[4])]) is fragment.outer
        assert (int(row[5]), int(row[6])) == (fragment.top, fragment.bottom)
        assert (int(row[7]), int(row[8])) == fragment.reach
        row = records.take("indices")
        assert tuple(int(v) for v in row[2:]) == fragment.indices and int(row[1]) == len(fragment.indices)
        row = records.take("edges")
        assert tuple(int(v) for v in row[2:]) == fragment.edges and int(row[1]) == len(fragment.edges)
        checks += 1
    for _ in range(int(records.take("probes")[1])):
        row = records.take("probe")
        point = Point(int(row[1]), int(row[2]))
        fragment = model.fragment_at(point)
        word, line = model.word_at(point), model.line_at(point)
        expected = (-1 if fragment is None else model.fragments.index(fragment), model.hit(point), word.start, word.end, line.start, line.end)
        assert tuple(int(v) for v in row[3:]) == expected, row
        checks += 1
    for _ in range(int(records.take("selects")[1])):
        row = records.take("select")
        selection = model.select(int(row[1]), int(row[2]))
        assert (int(row[3]), int(row[4])) == (selection.start, selection.end)
        checks += 1
    for _ in range(int(records.take("drags")[1])):
        row = records.take("drag")
        selection = model.select_at(Point(int(row[1]), int(row[2])), Point(int(row[3]), int(row[4])), Granularity[row[5].upper()])
        assert (int(row[6]), int(row[7])) == (selection.start, selection.end)
        checks += 1
    ranges = []
    for _ in range(int(records.take("ranges")[1])):
        row = records.take("range")
        selection = Selection(int(row[1]), int(row[2]))
        ranges.append(selection)
        if row[3] == "-1":
            try:
                model.rects(selection)
            except ValueError:
                checks += 1
                continue
            raise AssertionError(f"the reference did not raise for {row}")
        rects = model.rects(selection)
        assert int(row[3]) == len(rects)
        for rect in rects:
            assert tuple(int(v) for v in records.take("rect")[1:]) == (rect.x, rect.y, rect.width, rect.height)
        checks += 1
    data = []
    for _ in range(int(records.take("textdata")[1])):
        row = records.take("hard_breaks")
        breaks = [int(v) for v in row[2:]]

        def mapping(tag: str) -> dict[int, str]:
            fields = records.take(tag)
            assert len(fields) == 2 + 2 * int(fields[1])
            return {int(fields[2 + 2 * n]): unq(fields[3 + 2 * n]) for n in range(int(fields[1]))}

        data.append((breaks, mapping("separators"), mapping("atoms"), mapping("originals")))
    for _ in range(int(records.take("texts")[1])):
        row = records.take("text")
        breaks, separators, atoms, originals = data[int(row[3])]
        text = model.text(Selection(int(row[1]), int(row[2])), hard_breaks=breaks, separators=separators, atoms=atoms, originals=originals)
        assert text == unq(row[4]), (row, text)
        checks += 1
    return checks


def verify(path: Path) -> tuple[int, int]:
    text = path.read_bytes().decode("utf-8")
    assert text.endswith("\n") and "\r" not in text and "\t" not in text
    for line in text.split("\n"):
        assert not line.startswith(" ") and not line.endswith(" ") and "  " not in line, line
    records = Records(text)
    header = records.take("golden")
    assert int(header[1]) == FORMAT_VERSION and unq(header[2]) == "selection/" + path.stem
    cases = checks = 0
    while not records.done():
        row = records.take("case")
        assert row[2] == "selection"
        checks += verify_case(records)
        records.take("endcase")
        cases += 1
    return cases, checks


