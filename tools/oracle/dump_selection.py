GRANULARITIES = (Granularity.CHARACTER, Granularity.WORD, Granularity.LINE)


def line_position(cmds: Sequence[DrawCmd], line: Line) -> int:
    """
    Where in the command list a fragment's `Line` is: its identity in a golden.
    """
    for position, cmd in enumerate(cmds):
        if cmd is line:
            return position
    raise AssertionError("a fragment's line is not one of the commands")


def probe_points(model: SelectionModel, rng: Rng, limit: int) -> list[Point]:
    """
    Points worth asking about: on, either side of and between every edge that
    decides an answer, for the first lines and a sample of the rest, and a
    scatter over and around the whole.
    """
    points: list[Point] = []
    fragments = model.fragments
    if not fragments:
        return [Point(0, 0), Point(-5, 7), Point(1000, -1000)]
    left = min(f.line.x for f in fragments)
    right = max(f.line.x + f.line.width for f in fragments)
    top = min(f.top for f in fragments)
    bottom = max(f.bottom for f in fragments)
    wide = max(right - left, 4)
    tall = max(bottom - top, 4)

    def xs_of(fragment: Fragment) -> list[Scaled]:
        xs = [left - wide, fragment.line.x - 1, fragment.line.x, fragment.line.x + fragment.line.width - 1]
        xs += [fragment.line.x + fragment.line.width, fragment.line.x + fragment.line.width + 1, right + wide]
        edges = fragment.edges
        chosen = sorted({0, 1, 2, len(edges) // 2, len(edges) - 3, len(edges) - 2} & set(range(max(len(edges) - 1, 0))))
        for offset in chosen:
            a, b = edges[offset], edges[offset + 1]
            middle = (a + b) // 2
            xs += [a - 1, a, a + 1, middle - 1, middle, middle + 1, b - 1, b]
        return xs

    def ys_of(fragment: Fragment) -> list[Scaled]:
        return [fragment.top - 1, fragment.top, (fragment.top + fragment.bottom) // 2, fragment.bottom - 1, fragment.bottom]

    picked = list(range(len(fragments)))
    if len(picked) > 6:
        picked = sorted({0, 1, len(picked) // 2, len(picked) - 2, len(picked) - 1})
    for number in picked:
        fragment = fragments[number]
        for y in ys_of(fragment):
            for x in xs_of(fragment):
                points.append(Point(x, y))
    # Between each pair of neighbouring lines, and at each band's edges, at a
    # few x: which line a gap belongs to.
    for number, fragment in enumerate(fragments):
        for y in (fragment.top, fragment.bottom):
            for x in (fragment.line.x - 3, fragment.line.x + fragment.line.width // 2, right + 3):
                points.append(Point(x, y))
        if number + 1 < len(fragments):
            below = fragments[number + 1]
            gap = (fragment.bottom + below.top) // 2
            for y in (gap - 1, gap, gap + 1):
                points.append(Point(fragment.line.x + fragment.line.width // 3, y))
    for y in (top - tall, top - 1, bottom, bottom + 1, bottom + tall):
        for x in (left - 7, (left + right) // 2, right + 7):
            points.append(Point(x, y))
    for _ in range(60):
        points.append(Point(left - wide // 4 + rng.below(wide + wide // 2 + 1), top - tall // 4 + rng.below(tall + tall // 2 + 1)))

    unique: list[Point] = []
    seen: set[tuple[int, int]] = set()
    for point in points:
        key = (point.x, point.y)
        if key not in seen:
            seen.add(key)
            unique.append(point)
    if len(unique) > limit:
        # Keep the scatter and a spread of the rest.
        step = len(unique) / limit
        unique = [unique[int(i * step)] for i in range(limit)]
    return unique


def ranges_of(model: SelectionModel, rng: Rng) -> list[Selection]:
    """
    Ranges worth asking for: all of it, each line, across each break, single
    items, some at random, and ones a caller could build that `select` never
    would (backwards, past the end).
    """
    n = model.length
    out: list[Selection] = [Selection(0, n), Selection(0, 0), Selection(n, n), Selection(0, n + 5), Selection(3, 1)]
    fragments = model.fragments
    shown = fragments if len(fragments) <= 8 else [*fragments[:3], fragments[len(fragments) // 2], *fragments[-3:]]
    for fragment in shown:
        out.append(Selection(fragment.start, fragment.end))
        if fragment.end > fragment.start:
            out.append(Selection(fragment.start, fragment.start + 1))
            out.append(Selection(fragment.end - 1, fragment.end))
            out.append(Selection(fragment.start + 1, fragment.end))
            out.append(Selection(max(fragment.start - 1, 0), min(fragment.end + 1, n)))
            out.append(Selection(max(fragment.end - 2, 0), min(fragment.end + 2, n)))
    for _ in range(16):
        if n == 0:
            break
        a, b = rng.below(n + 1), rng.below(n + 1)
        out.append(model.select(a, b))
    unique: list[Selection] = []
    for selection in out:
        if selection not in unique:
            unique.append(selection)
    return unique


def text_data(model: SelectionModel, cmds: Sequence[DrawCmd], rng: Rng) -> list[dict[str, Any]]:
    """
    The data `text()` takes from the layers above it, several ways.
    """
    fragments = model.fragments
    atoms = sorted({cmd.index for cmd in cmds if isinstance(cmd, Atom)})
    glyphs = sorted({item.index for fragment in fragments for item in fragment.items if isinstance(item, Glyph)})
    starts = [fragment.start for fragment in fragments]
    plain: dict[str, Any] = {"hard_breaks": [], "separators": {}, "atoms": {}, "originals": {}}
    data = [plain]

    # Every other line is a source line: the code-block shape.
    data.append({**plain, "hard_breaks": sorted(set(starts[1::2]))})
    # Every line is.
    data.append({**plain, "hard_breaks": sorted(set(starts))})

    # Blocks, cells and markers, as the layer with the document would say.
    separators: dict[int, str] = {}
    for number, start in enumerate(starts):
        if number % 3 == 0:
            separators[start] = "\n\n"
        elif number % 3 == 1:
            separators[start] = "\n"
    for fragment in fragments:
        indices = fragment.indices
        if len(indices) >= 4:
            separators.setdefault(indices[len(indices) // 2], "\t")
            separators.setdefault(indices[1], " ")
    named = {index: f"${index}$" for index in atoms}
    data.append({**plain, "separators": dict(sorted(separators.items())), "atoms": named})

    # Atoms named and not, glyphs written as something else, separators that
    # are themselves blank or empty.
    originals: dict[int, str] = {}
    for index in glyphs[:: max(len(glyphs) // 7, 1)][:7]:
        originals[index] = rng.pick(["é", "ab", " ", "x ", "", "\n", "中文"])
    odd: dict[int, str] = {}
    for number, start in enumerate(starts):
        odd[start] = rng.pick(["", " ", "  ", "\t", "\n", " \n", "--"])
    data.append(
        {
            "hard_breaks": sorted(set(starts[::2])),
            "separators": dict(sorted(odd.items())),
            "atoms": {index: f"${index}$" for index in atoms[::2]},
            "originals": dict(sorted(originals.items())),
        }
    )
    return data


def selection_case(w: Writer, name: str, cmds: Sequence[DrawCmd], seed: int, *, probes: int = 260) -> None:
    rng = Rng(seed)
    model = SelectionModel.from_commands(cmds)
    w.case(name, "selection")
    emit_cmds(w, cmds)

    w.r("model", model.length, len(model.fragments))
    for fragment in model.fragments:
        reach_top, reach_bottom = fragment.reach
        w.r(
            "fragment",
            line_position(cmds, fragment.line),
            fragment.start,
            fragment.end,
            -1 if fragment.outer is None else line_position(cmds, fragment.outer),
            fragment.top,
            fragment.bottom,
            reach_top,
            reach_bottom,
        )
        w.r("indices", len(fragment.indices), *fragment.indices)
        w.r("edges", len(fragment.edges), *fragment.edges)

    points = probe_points(model, rng, probes)
    w.r("probes", len(points))
    for point in points:
        fragment = model.fragment_at(point)
        word = model.word_at(point)
        line = model.line_at(point)
        w.r(
            "probe",
            point.x,
            point.y,
            -1 if fragment is None else model.fragments.index(fragment),
            model.hit(point),
            word.start,
            word.end,
            line.start,
            line.end,
        )

    n = model.length
    pairs = [(0, 0), (0, n), (n, 0), (-3, 2), (2, -3), (n + 9, 1), (1, n + 9), (-1, -1), (n + 1, n + 2)]
    for _ in range(6):
        pairs.append((rng.below(n + 3) - 1, rng.below(n + 3) - 1))
    w.r("selects", len(pairs))
    for anchor, active in pairs:
        selection = model.select(anchor, active)
        w.r("select", anchor, active, selection.start, selection.end)

    drags = []
    for _ in range(24):
        drags.append((rng.pick(points), rng.pick(points), rng.pick(GRANULARITIES)))
    w.r("drags", len(drags))
    for anchor_point, active_point, granularity in drags:
        selection = model.select_at(anchor_point, active_point, granularity)
        w.r("drag", anchor_point.x, anchor_point.y, active_point.x, active_point.y, granularity, selection.start, selection.end)

    ranges = ranges_of(model, rng)
    w.r("ranges", len(ranges))
    for selection in ranges:
        try:
            rects = model.rects(selection)
        except ValueError:
            # A line whose indices do not ascend: `Fragment.rect_for` looks its
            # own items up again by index and does not find them.
            w.r("range", selection.start, selection.end, -1)
            continue
        w.r("range", selection.start, selection.end, len(rects))
        for rect in rects:
            w.r("rect", rect.x, rect.y, rect.width, rect.height)

    data = text_data(model, cmds, rng)
    w.r("textdata", len(data))
    for entry in data:
        w.r("hard_breaks", len(entry["hard_breaks"]), *entry["hard_breaks"])
        w.r("separators", len(entry["separators"]), *[v for k, s in entry["separators"].items() for v in (k, q(s))])
        w.r("atoms", len(entry["atoms"]), *[v for k, s in entry["atoms"].items() for v in (k, q(s))])
        w.r("originals", len(entry["originals"]), *[v for k, s in entry["originals"].items() for v in (k, q(s))])
    w.r("texts", len(ranges) * len(data))
    for selection in ranges:
        for number, entry in enumerate(data):
            text = model.text(
                selection,
                hard_breaks=entry["hard_breaks"],
                separators=entry["separators"],
                atoms=entry["atoms"],
                originals=entry["originals"],
            )
            w.r("text", selection.start, selection.end, number, q(text))
    w.end()


