    out.append(("ragged-right-fill", [*ragged, *text_line("cd", start=4, y=HEIGHT + LEADING)]))
    out.append(("only-fill", [Line(x=0, y=HEIGHT, width=100, height=HEIGHT, depth=DEPTH, start=0, end=2), fill(0, 0, width=50), fill(1, 50, width=50)]))
