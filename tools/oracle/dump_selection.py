def true_ranges(predicate: Callable[[str], bool]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = -1
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start < 0:
                start = codepoint
        elif start >= 0:
            ranges.append((start, codepoint - 1))
            start = -1
    if start >= 0:
        ranges.append((start, 0x10FFFF))
    return ranges


def emit_unicode_tables() -> str:
    """
    The block of src/selection.cpp between its GENERATED markers.
    """
    out = [
        "// clang-format off",
        "// GENERATED by tools/oracle/dump_selection.py --emit-unicode-tables. Do not edit.",
        f"// Python str.isalnum and str.isspace, Unicode {unicodedata.unidata_version}: inclusive ranges of the",
        "// codepoints for which each is true. Derived from the Unicode Character",
        "// Database, copyright Unicode, Inc., distributed under the Unicode License",
        "// (https://www.unicode.org/license.txt).",
    ]
    for name, predicate in (("ALNUM", str.isalnum), ("SPACE", str.isspace)):
        ranges = true_ranges(predicate)
        out.append(f"constexpr CodepointRange {name}_RANGES[] = {{")
        row: list[str] = []
        for first, last in ranges:
            row.append(f"{{0x{first:X}, 0x{last:X}}},")
            if len(row) == 5:
                out.append("    " + " ".join(row))
                row = []
        if row:
            out.append("    " + " ".join(row))
        out.append("};")
    out.append("// END GENERATED")
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


