def dump_runs() -> Writer:
    w = Writer(
        "runs",
        """
Styled runs handed straight to the reference's inline builder
(_Converter._append_text per run, then _text_block): bold, italic, bold-italic
and unbreakable code runs, kerning and white space at run boundaries, runs at
a size that is not the block's, list markers hung on the first line, a left
indent and a first-line indent.
""",
    )
    for px in SIZES_PX:
        for align in ALIGNS:
            theme = Theme.build(px, align=align)
            code = body(theme, code=True)
            events = [
                run(body(theme), "Plain words, then "),
                run(body(theme, bold=True), "bold words"),
                run(body(theme), " and "),
                run(body(theme, italic=True), "italic words"),
                run(body(theme), " and "),
                run(body(theme, bold=True, italic=True), "both at once"),
                run(body(theme), ", with "),
                run(code, "inline code --flag=value", False),
                run(body(theme), " that must not be cut, To Yo AV"),
                run(body(theme, bold=True), "AT"),
                run(body(theme, italic=True), "A"),
                run(body(theme), "V. "),
                run(body(theme), "Then a new run opens after the space and the paragraph is finished off."),
            ]
            runs_case(w, f"mixed-faces-{label(theme, px)}", theme, events, widths_px=(40.0, 240.0, 640.0))

    theme = Theme.build()
    left = Theme.build(align=Align.LEFT)
    regular, bold, italic = body(theme), body(theme, bold=True), body(theme, italic=True)
    code = body(theme, code=True)
    narrow = (120.0, 400.0)

    # A kern is looked up inside a run only: "AV" in one run kerns, "A" + "V"
    # in two does not, and no kern follows the last character of a run.
    runs_case(w, "kern-inside-a-run", theme, [run(regular, "AVAVA To Ty We fjord")], widths_px=narrow)
    runs_case(
        w,
        "kern-not-across-runs",
        theme,
        [run(regular, "A"), run(regular, "V"), run(regular, "A"), run(bold, "V"), run(regular, "A To"), run(regular, " Ty")],
        widths_px=narrow,
    )
    # White space at run boundaries: each run collapses its own, so a space
    # ending one run and a space opening the next are two glues.
    runs_case(
        w,
        "space-at-run-boundaries",
        theme,
        [run(regular, "one "), run(bold, " two"), run(regular, "  "), run(italic, "three"), run(regular, " "), run(regular, " four ")],
        widths_px=narrow,
    )
    runs_case(
        w,
        "leading-space-in-first-run",
        theme,
        [run(regular, " \t\n "), run(bold, "  lead"), run(regular, " tail  \n")],
        widths_px=narrow,
    )
    # Unbreakable runs: every space is preceded by an infinite penalty, a
    # leading space in the paragraph's first run is still dropped, and the
    # space factor carries across the run boundary.
    runs_case(
        w,
        "code-run-spaces",
        theme,
        [run(code, "  ls -la  /tmp ", False), run(regular, "then. "), run(code, "x  y", False), run(regular, " END."), run(code, " z", False)],
        widths_px=(40.0, 120.0, 400.0),
    )
    runs_case(
        w,
        "code-run-longer-than-the-line",
        left,
        [run(body(left), "Run "), run(body(left, code=True), "git commit --amend --no-edit --allow-empty", False), run(body(left), " now.")],
        widths_px=(120.0, 400.0),
    )
    runs_case(w, "empty-runs", theme, [run(regular, ""), run(bold, ""), run(regular, "a"), run(italic, ""), run(regular, " b")], widths_px=narrow)
    runs_case(w, "no-runs", theme, [], widths_px=narrow)
    # Hard breaks between runs, as markdown's inline walk emits them: the
    # glue a run ended with is removed first (and the penalty guarding it).
    for align in ALIGNS:
        aligned = Theme.build(align=align)
        plain = body(aligned)
        runs_case(
            w,
            f"hard-breaks-after-space-{align.name.lower()}",
            aligned,
            [
                run(plain, "aaa bbb "),
                HARDBREAK,
                run(plain, "ccc "),
                run(body(aligned, code=True), "d ", False),
                HARDBREAK,
                HARDBREAK,
                run(body(aligned, bold=True), "eee fff ggg hhh"),
            ],
            widths_px=(60.0, 240.0),
        )
    # Runs whose size is not the block's. The reference's own callers never
    # mix sizes in a block, but its builder takes any font per run, and the
    # strut is the block's: a taller run pushes its line past the strut and
    # the interline glue is no longer zero.
    big = FontSpec(Face.PROSE_BOLD, sp_from_px(34.0))
    small = FontSpec(Face.PROSE, sp_from_px(9.0))
    huge = FontSpec(Face.PROSE, sp_from_px(120.0))
    for name, aligned in (("justify", theme), ("left", left)):
        plain = body(aligned)
        runs_case(
            w,
            f"mixed-sizes-{name}",
            aligned,
            [
                run(plain, "Body text, then "),
                run(big, "Large gjpqy"),
                run(plain, " and back to body text for long enough to wrap, then "),
                run(small, "small print that runs on for a while (gjpqy)"),
                run(plain, " and body again to the end of the paragraph."),
            ],
            widths_px=(240.0, 640.0),
        )
        # Tall enough that baselineskip minus the depths goes under
        # lineskiplimit and the lineskip is used instead.
        runs_case(
            w,
            f"line-taller-than-the-leading-{name}",
            aligned,
            [run(plain, "before before before "), run(huge, "Hgy"), run(plain, " after after after after after after")],
            widths_px=(240.0, 640.0),
        )
    # Markers and indents.
    for align in (Align.JUSTIFY, Align.RIGHT):
        aligned = Theme.build(align=align)
        item = "A list item whose text runs on for long enough to need a continuation line or two."
        text_case(
            w,
            f"bullet-item-{align.name.lower()}",
            item,
            aligned,
            kind=BlockKind.BULLET_ITEM,
            marker="•",
            indent=aligned.list_indent,
            widths_px=(40.0, 240.0, 640.0),
        )
        # "10." is wider than the gutter was sized for at depth one of a
        # nested list; here it fits, and "100." below overfills the marker box.
        text_case(
            w,
            f"ordered-item-{align.name.lower()}",
            item,
            aligned,
            kind=BlockKind.ORDERED_ITEM,
            marker="10.",
            indent=2 * aligned.list_indent,
            widths_px=(240.0, 640.0),
        )
    text_case(w, "ordered-item-marker-wider-than-the-indent", "Short item.", theme, kind=BlockKind.ORDERED_ITEM, marker="1000000.", indent=theme.list_indent, widths_px=narrow)
    text_case(w, "marker-with-a-space-in-it", "Item text here.", theme, kind=BlockKind.BULLET_ITEM, marker="(a) i.", indent=3 * theme.list_indent, widths_px=narrow)
    text_case(w, "marker-on-empty-text", "", theme, kind=BlockKind.BULLET_ITEM, marker="•", indent=theme.list_indent, widths_px=narrow)
    text_case(w, "indent-without-marker", core.PROSE_A, theme, indent=theme.quote_indent, widths_px=(40.0, 240.0, 640.0))
    text_case(w, "indent-wider-than-the-column", "Some words to set.", left, indent=sp_from_px(300.0), widths_px=(240.0, 300.0, 301.0))
    for align in ALIGNS:
        aligned = Theme.build(align=align)
        indented = with_first_line_indent(aligned, sp_from_px(24.0))
        text_case(w, f"first-line-indent-{align.name.lower()}", core.PROSE_A, indented, indent=sp_from_px(10.0), widths_px=(40.0, 240.0, 640.0))
    text_case(w, "first-line-indent-wider-than-the-column", "Some words to set.", with_first_line_indent(theme, sp_from_px(100.0)), widths_px=(60.0, 99.0, 240.0))
    text_case(w, "first-line-indent-on-empty-text", "", with_first_line_indent(theme, sp_from_px(24.0)), widths_px=narrow)
    return w


def with_first_line_indent(theme: Theme, indent: Scaled) -> Theme:
    """
    `theme` with its paragraphs given a first-line indent, which no built theme has.
    """
    style = theme.style(BlockKind.PARAGRAPH)
    blocks = {**theme.blocks, BlockKind.PARAGRAPH: replace(style, first_line_indent=indent)}
    return replace(theme, blocks=blocks)


