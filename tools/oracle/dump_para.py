def stand_in_faces(theme: Theme) -> tuple[Face, Face, Face]:
    """
    The faces `_stand_in` reads: the prose face, the math face, the code face.
    """
    return (theme.faces.regular, Face.MATH, theme.faces.code)


def emit_block_inputs(w: Writer, theme: Theme, kind: BlockKind, block: markdown.TextBlock) -> None:
    """
    Every value the composition path reads from the Theme, for this block.
    """
    style = block.style
    w.r(
        "block",
        float(theme.px_per_inch),
        theme.spacing,
        style.align,
        kind,
        q(style.font.key),
        block.left_indent,
        style.first_line_indent,
        theme.marker_gap,
    )
    w.r("faces", *[q(face.value) for face in stand_in_faces(theme)])
    emit_skip(w, style.interline)
    w.r("strut", style.strut.height, style.strut.depth)


def emit_assembly(
    w: Writer,
    name: str,
    block: markdown.TextBlock,
    theme: Theme,
    width: Scaled,
    measure: Any,
    broken: Sequence[Box],
) -> None:
    """
    What `advtext.ui` does with one block after the breaker returns.

    `broken` is `break_paragraph`'s boxes for the same inputs, already written
    as `packed` records; this asserts the UI's path reaches the same ones and
    writes only what it adds: the hung marker, the strut, the vertical list,
    the packed vbox and the shipped commands.
    """
    params = ui.PROSE_BREAKING
    lines = ui._text_boxes(block, theme, width, measure, params)
    assert len(lines) == len(broken)
    w.r("assemble", q(name), width)
    if block.marker:
        assert lines[1:] == list(broken[1:]) and lines[0] != broken[0]
        w.r("hung")
        emit_node(w, lines[0])
    else:
        assert lines == list(broken), "advtext.ui._text_boxes disagrees with the recorded run"
    strut = block.style.strut
    strutted = ui._block_boxes(block, theme, width, measure, params)
    assert len(strutted) == len(lines)
    w.r("strutted", len(strutted))
    for line, set_line in zip(lines, strutted):
        # The strut changes two numbers of the box and nothing else.
        assert set_line == replace(line, height=set_line.height, depth=set_line.depth)
        assert set_line.height == max(line.height, strut.height)
        assert set_line.depth == max(line.depth, strut.depth)
        w.r("dims", set_line.width, set_line.height, set_line.depth, set_line.shift_amount)
    vlist = ui._stacked((block,), theme, width, measure, params, depth=0, memo=None)
    w.r("vlist", len(vlist))
    at = 0
    for node in vlist:
        if isinstance(node, Box):
            assert node == strutted[at]
            w.r("ref", at)
            at += 1
        else:
            assert isinstance(node, (Glue, Kern))
            emit_node(w, node)
    assert at == len(strutted)
    w.r("endvlist")
    vbox = ui.compose_blocks((block,), theme, width, measure)
    assert vbox == vpack(vlist).box
    origin = Point(0, vbox.height)
    w.r("vbox", vbox.width, vbox.height, vbox.depth)
    w.r("origin", origin.x, origin.y)
    emit_cmds(w, ship(vbox, origin, measure=measure))
    w.r("endassemble")


MEASURE = char_measure(fontlib_metrics)


def emit_case(
    w: Writer,
    name: str,
    source_kind: str,
    source: str,
    theme: Theme,
    kind: BlockKind,
    events: Sequence[Event],
    *,
    widths_px: Sequence[float] = WIDTHS_PX,
    indent: Scaled = 0,
    marker: str = "",
    expect: markdown.TextBlock | None = None,
    widths: Sequence[tuple[str, Scaled]] | None = None,
) -> markdown.TextBlock:
    """
    One block: its inputs, its material, and its setting at each width.

    `expect`, when given, is the block the reference's public entry built from
    `source`; the direct driver must reproduce it from `events` alone (its
    link spans aside: they index the material and are not layout). `widths`
    replaces the pixel columns with named widths in scaled points.
    """
    assert kind not in (BlockKind.CODE, BlockKind.RULE, BlockKind.TABLE)
    consulted = Consulted()
    hung = (theme.font_for(kind, Emphasis()).key, marker) if marker else None
    block = build_block(theme, consulted.resolve, kind, events, indent=indent, marker=hung)
    if expect is not None:
        assert block == replace(expect, links=()), f"{name}: the recorded runs do not rebuild the block"
    assert not block.quote_depth and not block.formulas

    w.case(name, "para")
    w.r("source", source_kind, q(source))
    emit_block_inputs(w, theme, kind, block)
    w.r("runs", len(events))
    for event in events:
        if event[0] == "run":
            w.r("run", q(event[1]), event[2], q(event[3]))
        else:
            w.r("hardbreak")
    w.r("endruns")
    if hung is not None:
        w.r("marker", q(hung[0]), q(hung[1]))
    consulted.emit(w)
    emit_measure(w, MEASURE, block.material, block.marker)
    emit_nodes(w, "material", block.material)
    if hung is not None:
        emit_nodes(w, "marker", block.marker)
    unshrinkable_written = False
    if widths is None:
        widths = [(f"ui-{px:g}px", sp_from_px(px, theme.px_per_inch)) for px in widths_px]
    for run_name, width in widths:
        list_name, material, shape, params = core._ui_run(block, width, ui.PROSE_BREAKING)
        if list_name == "unshrinkable" and not unshrinkable_written:
            emit_nodes(w, "unshrinkable", material)
            unshrinkable_written = True
        paragraph = emit_run(w, run_name, list_name, material, shape, params, MEASURE, None)
        emit_assembly(w, run_name, block, theme, width, MEASURE, paragraph.boxes)
    w.end()
    return block


def text_case(
    w: Writer,
    name: str,
    text: str,
    theme: Theme,
    *,
    hard_breaks: bool = False,
    kind: BlockKind = BlockKind.PARAGRAPH,
    marker: str = "",
    indent: Scaled = 0,
    widths_px: Sequence[float] = WIDTHS_PX,
) -> markdown.TextBlock:
    """
    Plain text through `markdown.text_block`, the reference's public entry.
    """
    with Capture().installed() as capture:
        expect = markdown.text_block(
            text, theme, fontlib_metrics, kind=kind, hard_breaks=hard_breaks, marker=marker, indent=indent
        )
    (found,) = [entry for entry in capture.blocks if entry[0] is expect]
    return emit_case(
        w,
        name,
        "text-hard-breaks" if hard_breaks else "text",
        text,
        theme,
        kind,
        found[1],
        widths_px=widths_px,
        indent=indent,
        marker=marker,
        expect=expect,
    )


def runs_case(
    w: Writer,
    name: str,
    theme: Theme,
    events: Sequence[Event],
    *,
    kind: BlockKind = BlockKind.PARAGRAPH,
    indent: Scaled = 0,
    widths_px: Sequence[float] = WIDTHS_PX,
    widths: Sequence[tuple[str, Scaled]] | None = None,
) -> markdown.TextBlock:
    """
    Styled runs handed straight to the reference's inline builder.
    """
    return emit_case(w, name, "runs", "", theme, kind, events, widths_px=widths_px, indent=indent, widths=widths)


def label(theme: Theme, px: float) -> str:
    return f"{px:g}px-{theme.style(BlockKind.PARAGRAPH).align.name.lower()}"


def body(theme: Theme, **emphasis: bool) -> FontSpec:
    return theme.font_for(BlockKind.PARAGRAPH, Emphasis(**emphasis))


