def dump_prose() -> Writer:
    w = Writer(
        "prose",
        """
Plain text through markdown.text_block, the reference's public entry for text
with no markdown in it: one run in the block's own face. The sentence cases
hold the space-factor rule (advtext.style.space_factor_after, interword_glue)
under each Spacing, with upper-case letters outside A-Z before the period.
""",
    )
    for px in SIZES_PX:
        for align in ALIGNS:
            theme = Theme.build(px, align=align)
            text_case(w, f"prose-{label(theme, px)}", core.PROSE_A, theme)
    hidpi = Theme.build(16.0, 144.0)
    text_case(w, "prose-16px-at-144-px-per-inch", core.PROSE_A, hidpi, widths_px=(360.0, 960.0))
    for spacing in Spacing:
        for align in (Align.JUSTIFY, Align.LEFT):
            theme = Theme.build(spacing=spacing, align=align)
            text_case(
                w,
                f"sentences-{spacing.name.lower().replace('_', '-')}-{align.name.lower()}",
                SENTENCES,
                theme,
                widths_px=(240.0, 640.0),
            )
    mono = Theme.build(faces=Faces.mono())
    text_case(w, "prose-monospace-theme", core.PROSE_A, mono, widths_px=(240.0, 640.0))
    for kind in (BlockKind.HEADING_1, BlockKind.HEADING_5, BlockKind.HEADING_6):
        theme = Theme.build()
        text_case(
            w,
            f"heading-{kind.name.lower().replace('_', '-')}",
            "A heading long enough to wrap onto a second line. Or a third?",
            theme,
            kind=kind,
            widths_px=(120.0, 400.0),
        )
    return w


