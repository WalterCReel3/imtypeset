class _RecordingMetrics:
    """
    One face at one size, noting each question the composition path asks it.
    """

    def __init__(self, key: str, inner: Any, log: Consulted) -> None:
        self._key = key
        self._inner = inner
        self._log = log

    @property
    def space_width(self) -> float:
        value = float(self._inner.space_width)
        self._log.space[self._key] = value
        return value

    def has(self, codepoint: int) -> bool:
        value = bool(self._inner.has(codepoint))
        self._log.has[(self._key, codepoint)] = value
        return value

    def kern(self, codepoint: int, following: int) -> float:
        value = float(self._inner.kern(codepoint, following))
        self._log.kern[(self._key, codepoint, following)] = value
        return value

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)


@dataclass(slots=True)
class Consulted:
    """
    Every metrics answer one case's material was built from.
    """

    space: dict[str, float] = field(default_factory=dict)
    has: dict[tuple[str, int], bool] = field(default_factory=dict)
    kern: dict[tuple[str, int, int], float] = field(default_factory=dict)

    def resolve(self, key: str) -> Any:
        return _RecordingMetrics(key, fontlib_metrics(key), self)

    def emit(self, w: Writer) -> None:
        for key in sorted(self.space):
            w.r("space_width", q(key), self.space[key])
        for key, codepoint in sorted(self.has):
            w.r("has", q(key), codepoint, self.has[(key, codepoint)])
        for key, codepoint, following in sorted(self.kern):
            w.r("kern", q(key), codepoint, following, self.kern[(key, codepoint, following)])


