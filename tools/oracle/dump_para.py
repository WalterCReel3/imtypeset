def sample_paragraphs(theme: Theme) -> list[tuple[markdown.TextBlock, list[Event]]]:
    """
    Every top-level paragraph of demo/sample.md whose runs rebuild it exactly.

    That leaves out a paragraph inside a list or a quote (it is another block
    kind) and nothing else the document contains; the count is asserted by the
    caller so a change in the reference's demo is seen.
    """
    source = (REFERENCE / "demo" / "sample.md").read_text(encoding="utf-8")
    with Capture().installed() as capture:
        document = markdown.build_document(source, theme, fontlib_metrics)
    out: list[tuple[markdown.TextBlock, list[Event]]] = []
    for block in document.blocks:
        if not isinstance(block, markdown.TextBlock) or block.kind is not BlockKind.PARAGRAPH:
            continue
        (found,) = [entry for entry in capture.blocks if entry[0] is block]
        _, events, indent, depth = found
        if indent or depth or block.marker or block.formulas:
            continue
        if build_block(theme, fontlib_metrics, block.kind, events) != replace(block, links=()):
            continue
        out.append((block, events))
    return out


def dump_sample() -> Writer:
    w = Writer(
        "sample",
        """
Paragraphs of the reference's demo/sample.md, as markdown.build_document built
them, at two body sizes, four alignments and five column widths. The runs are
the reference's own _append_text calls for the block (emphasis, inline code and
soft line ends included); markdown itself is not ported and is not an input.
""",
    )
    chosen: list[int] | None = None
    for px in SIZES_PX:
        for align in ALIGNS:
            theme = Theme.build(px, align=align)
            paragraphs = sample_paragraphs(theme)
            if chosen is None:
                assert len(paragraphs) == SAMPLE_PARAGRAPHS, len(paragraphs)
                by_length = sorted(range(len(paragraphs)), key=lambda i: (len(paragraphs[i][0].material), i))
                fonts = [len({e[1] for e in events if e[0] == "run"}) for _, events in paragraphs]
                most_faces = max(range(len(paragraphs)), key=lambda i: (fonts[i], -i))
                chosen = list(
                    dict.fromkeys((by_length[-1], by_length[len(by_length) // 2], by_length[0], most_faces))
                )
                assert len(paragraphs[by_length[-1]][0].material) == 635
            assert len(paragraphs) == SAMPLE_PARAGRAPHS
            for index in chosen:
                block, events = paragraphs[index]
                emit_case(
                    w,
                    f"sample-paragraph-{index}-{label(theme, px)}",
                    "markdown-block-of-demo/sample.md",
                    "",
                    theme,
                    BlockKind.PARAGRAPH,
                    events,
                    expect=block,
                )
    return w


