# ("run", font key, breakable, text) or ("hardbreak",)
Event = tuple[Any, ...]


def run(font: FontSpec | str, text: str, breakable: bool = True) -> Event:
    return ("run", font if isinstance(font, str) else font.key, breakable, text)


HARDBREAK: Event = ("hardbreak",)


@dataclass(slots=True)
class Capture:
    """
    The `_append_text` and `_fill_and_break` calls behind each block built.

    Installed around a call into `markdown.text_block` or
    `markdown.build_document`; the reference's code is wrapped in memory and
    nothing is changed on disk.
    """

    blocks: list[tuple[markdown.TextBlock, list[Event], Scaled, int]] = field(default_factory=list)
    _by_run: dict[int, list[Event]] = field(default_factory=dict)
    _pinned: list[object] = field(default_factory=list)
    _last: list[Event] | None = None

    @contextlib.contextmanager
    def installed(self) -> Iterator[Capture]:
        converter = markdown._Converter
        append_text = converter._append_text
        text_block = converter._text_block
        fill_and_break = markdown._fill_and_break

        def recording_append(conv: Any, target: Any, text: str, font: FontSpec, breakable: bool) -> None:
            if id(target) not in self._by_run:
                self._by_run[id(target)] = []
                self._pinned.append(target)  # so the id is not reused
            self._last = self._by_run[id(target)]
            self._last.append(run(font, text, breakable))
            append_text(conv, target, text, font, breakable)

        def recording_block(conv: Any, kind: BlockKind, target: Any) -> markdown.TextBlock:
            indent, depth = conv._indent, conv._quote_depth
            block = text_block(conv, kind, target)
            self.blocks.append((block, list(self._by_run.get(id(target), [])), indent, depth))
            return block

        def recording_break(align: Align) -> tuple[Node, ...]:
            if self._last is not None:
                self._last.append(HARDBREAK)
            return fill_and_break(align)

        converter._append_text = recording_append  # type: ignore[method-assign]
        converter._text_block = recording_block  # type: ignore[method-assign]
        markdown._fill_and_break = recording_break
        try:
            yield self
        finally:
            converter._append_text = append_text  # type: ignore[method-assign]
            converter._text_block = text_block  # type: ignore[method-assign]
            markdown._fill_and_break = fill_and_break


def build_block(
    theme: Theme,
    resolve: Callable[[str], Any],
    kind: BlockKind,
    events: Sequence[Event],
    *,
    indent: Scaled = 0,
    marker: tuple[str, str] | None = None,
) -> markdown.TextBlock:
    """
    The direct driver: recorded runs in, the reference's `TextBlock` out.

    Exactly the calls `markdown.text_block` and `_Converter._inline` make, in
    their order. A `hardbreak` is what `_inline` does for one: `_unskip`, then
    `_fill_and_break` for the block's alignment. `marker` is (font key, text),
    built as `_marker_material` builds it: unbreakable, in a run of its own.
    """
    converter = markdown._Converter(theme, resolve)
    converter._indent = indent
    if marker is not None:
        hung = markdown._Run()
        converter._append_text(hung, marker[1], parse_font_key(marker[0]), False)
        converter._pending_marker = tuple(hung.nodes)
    built = markdown._Run()
    for event in events:
        if event[0] == "run":
            converter._append_text(built, event[3], parse_font_key(event[1]), event[2])
        else:
            markdown._unskip(built, [])
            built.nodes.extend(markdown._fill_and_break(theme.style(kind).align))
    return converter._text_block(kind, built)


