class _TableMetrics:
    """
    A face that knows only what a case recorded, and fails on anything else.
    """

    def __init__(self, key: str, tables: _Tables) -> None:
        self._key = key
        self._tables = tables

    @property
    def space_width(self) -> float:
        return self._tables.space[self._key]

    def has(self, codepoint: int) -> bool:
        return self._tables.has[(self._key, codepoint)]

    def kern(self, codepoint: int, following: int) -> float:
        return self._tables.kern[(self._key, codepoint, following)]


@dataclass(slots=True)
class _Tables:
    space: dict[str, float] = field(default_factory=dict)
    has: dict[tuple[str, int], bool] = field(default_factory=dict)
    kern: dict[tuple[str, int, int], float] = field(default_factory=dict)

    def read(self, records: Records) -> None:
        while records.peek()[0] in ("space_width", "has", "kern"):
            row = records.take()
            if row[0] == "space_width":
                self.space[unq(row[1])] = float.fromhex(row[2])
            elif row[0] == "has":
                self.has[(unq(row[1]), int(row[2]))] = row[3] == "1"
            else:
                self.kern[(unq(row[1]), int(row[2]), int(row[3]))] = float.fromhex(row[4])

    def resolve(self, key: str) -> Any:
        return _TableMetrics(key, self)


def _token_enum(cls: Any, token: str) -> Any:
    return cls[token.upper()]


def _read_spec(records: Records, role: str) -> GlueSpec:
    row = records.take("spec")
    assert row[1] == role, row
    return core._spec(row[2:7])


def _read_shape(records: Records) -> ParShape:
    row = records.take("shape")
    return ParShape(tuple(LineSpec(int(row[2 + 2 * i]), int(row[3 + 2 * i])) for i in range(int(row[1]))))


def _read_params(records: Records) -> LineBreakParams:
    row = records.take("params")
    return LineBreakParams(
        *[int(v) for v in row[1:10]],
        left_skip=_read_spec(records, "left_skip"),
        right_skip=_read_spec(records, "right_skip"),
        par_fill_skip=_read_spec(records, "par_fill_skip"),
        first_fit=row[10] == "1",
    )


def _theme_from_records(
    px_per_inch: float,
    spacing: Spacing,
    align: Align,
    kind: BlockKind,
    font: str,
    first_line_indent: Scaled,
    marker_gap: Scaled,
    faces: Sequence[str],
    interline: InterlineSkip,
) -> Theme:
    """
    A Theme holding the recorded values and nothing else.

    Every field the records do not carry is zero, so a path that read one
    would not reproduce the recorded answers.
    """
    assert faces[1] == Face.MATH.value
    style = BlockStyle(font=parse_font_key(font), interline=interline, align=align, first_line_indent=first_line_indent)
    return Theme(
        blocks={kind: style},
        px_per_inch=px_per_inch,
        marker_gap=marker_gap,
        list_indent=0,
        quote_indent=0,
        rule_thickness=0,
        quote_rule_thickness=0,
        cell_padding=0,
        table_rule_thickness=0,
        spacing=spacing,
        faces=Faces(regular=Face(faces[0]), code=Face(faces[2])),
    )


def verify_para(records: Records) -> int:
    row = records.take("source")
    source_kind, source = row[1], unq(row[2])
    row = records.take("block")
    px_per_inch = float.fromhex(row[1])
    spacing, align, kind = _token_enum(Spacing, row[2]), _token_enum(Align, row[3]), _token_enum(BlockKind, row[4])
    font, left_indent, first_line_indent, marker_gap = unq(row[5]), int(row[6]), int(row[7]), int(row[8])
    faces = [unq(token) for token in records.take("faces")[1:]]
    interline = read_skip(records)
    theme = _theme_from_records(px_per_inch, spacing, align, kind, font, first_line_indent, marker_gap, faces, interline)
    row = records.take("strut")
    strut = Strut(int(row[1]), int(row[2]))
    assert theme.style(kind).strut == strut == Strut.filling(interline.baselineskip.width)

    events: list[Event] = []
    for _ in range(int(records.take("runs")[1])):
        row = records.take()
        events.append(("run", unq(row[1]), row[2] == "1", unq(row[3])) if row[0] == "run" else HARDBREAK)
        assert row[0] in ("run", "hardbreak")
    records.take("endruns")
    marker = None
    if records.peek()[0] == "marker":
        row = records.take()
        marker = (unq(row[1]), unq(row[2]))
    tables = _Tables()
    tables.read(records)
    measure = read_measure(records)
    if measure is None:
        measure = lambda node: CharDimens(0, 0, 0)  # noqa: E731 - a case with no characters

    block = build_block(theme, tables.resolve, kind, events, indent=left_indent, marker=marker)
    lists: dict[str, list[Node]] = {}
    name, nodes = read_nodes(records)
    assert name == "material" and tuple(nodes) == block.material
    lists[name] = nodes
    if marker is not None:
        name, nodes = read_nodes(records)
        assert name == "marker" and tuple(nodes) == block.marker
    assert block.left_indent == left_indent

    # The public entries the `source` names, on the recorded tables.
    if source_kind in ("text", "text-hard-breaks"):
        # Only where the cut-down Theme still resolves the block's own face.
        assert theme.font_for(kind, Emphasis()).key == font
        public = markdown.text_block(
            source,
            theme,
            tables.resolve,
            kind=kind,
            hard_breaks=source_kind == "text-hard-breaks",
            marker=marker[1] if marker else "",
            indent=left_indent,
        )
        assert public == block

    checks = 1
    while records.peek()[0] != "endcase":
        if records.peek()[0] == "nodes":
            name, nodes = read_nodes(records)
            assert name == "unshrinkable" and tuple(nodes) == ui._unshrinkable(block.material)
            lists[name] = nodes
            continue
        row = records.take("break")
        run_name, list_name = unq(row[1]), row[2]
        shape = _read_shape(records)
        params = _read_params(records)
        assert list_name == ("material" if align is Align.JUSTIFY else "unshrinkable")
        assert params == replace(ui._skips(align, ui.PROSE_BREAKING), first_fit=align is not Align.JUSTIFY)
        got, breaks, prepared = core.break_with_positions(lists[list_name], shape, params, measure)
        row = records.take("paragraph")
        assert (len(got.lines), got.total_demerits, got.pass_used.name.lower(), prepared) == (int(row[1]), int(row[2]), row[3], int(row[4]))
        row = records.take("breaks")
        assert [(int(row[2 + 2 * i]), row[3 + 2 * i]) for i in range(int(row[1]))] == breaks
        lines = [read_packed(records) for _ in got.lines]
        assert list(got.lines) == lines
        records.take("endbreak")

        row = records.take("assemble")
        assert unq(row[1]) == run_name
        width = int(row[2])
        assert ui._shape(block, width) == shape
        if run_name.startswith("ui-"):
            assert sp_from_px(float(run_name[3:-2]), px_per_inch) == width
        boxes = ui._text_boxes(block, theme, width, measure, ui.PROSE_BREAKING)
        if records.peek()[0] == "hung":
            records.take()
            assert marker is not None and read_node(records) == boxes[0]
            assert boxes[1:] == [line.box for line in lines[1:]]
        else:
            assert marker is None and boxes == [line.box for line in lines]
        strutted = ui._block_boxes(block, theme, width, measure, ui.PROSE_BREAKING)
        assert int(records.take("strutted")[1]) == len(strutted)
        for line, set_line in zip(boxes, strutted):
            row = records.take("dims")
            assert set_line == replace(line, height=int(row[2]), depth=int(row[3]))
            assert (set_line.width, set_line.shift_amount) == (int(row[1]), int(row[4]))
        vlist = ui._stacked((block,), theme, width, measure, ui.PROSE_BREAKING, depth=0, memo=None)
        assert int(records.take("vlist")[1]) == len(vlist)
        for node in vlist:
            if records.peek()[0] == "ref":
                assert node == strutted[int(records.take()[1])]
            else:
                assert read_node(records) == node
        records.take("endvlist")
        vbox = ui.compose_blocks((block,), theme, width, measure)
        row = records.take("vbox")
        assert (vbox.width, vbox.height, vbox.depth) == tuple(int(v) for v in row[1:4])
        row = records.take("origin")
        origin = Point(int(row[1]), int(row[2]))
        assert origin == Point(0, vbox.height)
        assert same_cmds(ship(vbox, origin, measure=measure), read_cmds(records))
        records.take("endassemble")
        checks += 1
    return checks


def verify_table(records: Records) -> int:
    checks = 0
    theme = Theme.build()
    style = theme.style(BlockKind.PARAGRAPH)
    while records.peek()[0] != "endcase":
        row = records.take()
        tag = row[0]
        if tag in ("const", "spec", "params"):
            pass  # constants: compared by the port, restated by nothing here
        elif tag == "skips":
            align = _token_enum(Align, row[1])
            chosen = ui._skips(align, ui.PROSE_BREAKING)
            assert (align is not Align.JUSTIFY) == (row[2] == "1")
            assert chosen.left_skip == _read_spec(records, "left_skip")
            assert chosen.right_skip == _read_spec(records, "right_skip")
            assert chosen.par_fill_skip == _read_spec(records, "par_fill_skip")
        elif tag == "fill_and_break":
            name, nodes = read_nodes(records)
            assert name == "fill" and tuple(nodes) == markdown._fill_and_break(_token_enum(Align, row[1]))
        elif tag == "shape_for":
            block = markdown.TextBlock(BlockKind.PARAGRAPH, replace(style, first_line_indent=int(row[3])), (), left_indent=int(row[2]))
            assert ui._shape(block, int(row[1])) == _read_shape(records)
        elif tag == "nodes":
            records.at -= 1
            name, nodes = read_nodes(records)
            other, out = read_nodes(records)
            assert (name, other) == ("in", "out") and ui._unshrinkable(tuple(nodes)) == tuple(out)
        elif tag == "strut_filling":
            strut = Strut.filling(int(row[1]))
            assert (strut.height, strut.depth) == (int(row[2]), int(row[3]))
        elif tag == "strut_applied":
            box = Box(BoxKind.HLIST, (), height=int(row[3]), depth=int(row[4]))
            applied = Strut(int(row[1]), int(row[2])).applied_to(box)
            assert (applied.height, applied.depth) == (int(row[5]), int(row[6]))
        else:
            raise AssertionError(row)
        checks += 1
    return checks


def verify_standin(records: Records) -> int:
    faces = [unq(token) for token in records.take("faces")[1:]]
    assert faces[1] == Face.MATH.value
    theme = replace(Theme.build(), faces=Faces(regular=Face(faces[0]), code=Face(faces[2])))
    tables = _Tables()
    tables.read(records)
    checks = 0
    while records.peek()[0] != "endcase":
        row = records.take("stand_in")
        key, codepoint = unq(row[1]), int(row[2])
        assert tables.has[(key, codepoint)] is False
        assert markdown._stand_in(theme, tables.resolve, key, codepoint) == (unq(row[3]), int(row[4]))
        checks += 1
    return checks


def verify_ranges(records: Records) -> int:
    assert unq(records.take("unicode_version")[1]) == unicodedata.unidata_version
    predicates = dict(PREDICATES)
    checks = 0
    while records.peek()[0] != "endcase":
        row = records.take("predicate")
        ranges = [(int(r[1]), int(r[2])) for r in (records.take("range") for _ in range(int(row[2])))]
        assert ranges == true_ranges(predicates[row[1]])
        assert sum(last - first + 1 for first, last in ranges) == int(row[3])
        checks += 1
    return checks


VERIFIERS: dict[str, Callable[[Records], int]] = {
    "para": verify_para,
    "table": verify_table,
    "standin": verify_standin,
    "ranges": verify_ranges,
}


def verify(path: Path) -> tuple[int, int]:
    text = path.read_bytes().decode("utf-8")
    assert text.endswith("\n") and "\r" not in text and "\t" not in text
    for line in text.split("\n"):
        assert not line.startswith(" ") and not line.endswith(" ") and "  " not in line, line
    records = Records(text)
    header = records.take("golden")
    assert int(header[1]) == FORMAT_VERSION and unq(header[2]) == "para/" + path.stem
    cases = checks = 0
    while not records.done():
        row = records.take("case")
        try:
            checks += VERIFIERS[row[2]](records)
        except Exception:
            print(f"{path.name}: case {unq(row[1])} failed near record {records.at}", file=sys.stderr)
            raise
        records.take("endcase")
        cases += 1
    return cases, checks


