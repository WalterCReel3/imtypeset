def true_ranges(predicate: Callable[[str], bool]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = -1
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start < 0:
                start = codepoint
        elif start >= 0:
            ranges.append((start, codepoint - 1))
            start = -1
    if start >= 0:
        ranges.append((start, 0x10FFFF))
    return ranges


def dump_unicode() -> Writer:
    w = Writer(
        "unicode",
        f"""
The Python str predicates paragraph assembly branches on, over every codepoint
0..0x10FFFF, as inclusive ranges where the predicate is TRUE: str.isspace()
(interword glue, and never stood in for), str.isupper() (the space factor) and
the general categories Cc, Cf, Mn, Me (never stood in for). The same records
as tests/golden/math/unicode.golden, which holds these and more; this script
asserts the two agree when that file is present.
Unicode {unicodedata.unidata_version} (this interpreter's unicodedata).
These ranges are derived from the Unicode Character Database, which is
copyright Unicode, Inc. and distributed under the Unicode License
(https://www.unicode.org/license.txt). The licence's notice is to accompany
copies of the data; THIRD-PARTY.md is where this tree keeps such notices.
""",
    )
    w.case("predicates", "ranges")
    w.r("unicode_version", q(unicodedata.unidata_version))
    for name, predicate in PREDICATES:
        ranges = true_ranges(predicate)
        w.r("predicate", name, len(ranges), sum(last - first + 1 for first, last in ranges))
        for first, last in ranges:
            w.r("range", first, last)
    w.end()
    return w


def agrees_with_math_unicode(text: str) -> bool | None:
    """
    Whether para/unicode.golden's predicates equal math/unicode.golden's.

    None when that file is not there to compare with.
    """
    other = ROOT / "tests" / "golden" / "math" / "unicode.golden"
    if not other.exists():
        return None

    def tables(source: str) -> dict[str, list[str]]:
        out: dict[str, list[str]] = {}
        name = ""
        for line in source.split("\n"):
            if line.startswith("predicate "):
                name = line.split(" ")[1]
                out[name] = [line]
            elif line.startswith("range "):
                out[name].append(line)
            elif line.startswith("unicode_version "):
                out["version"] = [line]
        return out

    ours, theirs = tables(text), tables(other.read_text(encoding="utf-8"))
    return all(theirs.get(name) == rows for name, rows in ours.items())


