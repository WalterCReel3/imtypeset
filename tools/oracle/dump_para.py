#!/usr/bin/env python3
"""
Dump paragraph-assembly goldens from the Python reference (imgui-adv-text).

Writes tests/golden/para/*.golden: what turns styled text, a width and an
alignment into the line boxes of one paragraph and the commands that draw
them. The record vocabulary is tools/oracle/FORMAT-para.md, over
tools/oracle/FORMAT.md, whose node, pack, line-break and draw-command records
are reused verbatim and written by the functions of the sibling script
dump_core.py, imported here.

Run from the imtypeset repository root, with the reference's interpreter:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=build/advtext-reference \\
        ../imgui-adv-text/.venv/bin/python -P -B tools/oracle/dump_para.py

    ... dump_para.py --verify   re-reads every golden with a reader written
                                from the two FORMAT documents, rebuilds each
                                case from its records alone -- a Theme holding
                                only the recorded values, a metrics resolver
                                answering only from the recorded tables -- and
                                replays it through the reference.

The script only reads the reference. Output is deterministic: a second run is
byte-identical to the first.

Every expectation is an answer of one of the reference's own functions, called
directly and not re-implemented:

    text -> material   advtext.markdown._Converter._append_text, _text_block,
                       _unskip, _fill_and_break, _char_node / _stand_in
    skips and shape    advtext.ui._skips, _shape, _unshrinkable
    lines              advtext.linebreak.break_paragraph, as advtext.ui
                       ._text_boxes calls it (asserted equal to _text_boxes)
    strut              advtext.ui._block_boxes (advtext.style.Strut)
    vertical list      advtext.ui._stacked over the one block
    the vbox           advtext.ui.compose_blocks over the one block
    commands           advtext.shipout.ship

A case's INPUT is a sequence of styled runs. Where the case starts from plain
text or from markdown, the runs are the calls the reference itself made to
`_append_text` while building the block through its public entry
(`markdown.text_block`, `markdown.build_document`), captured by wrapping that
method in memory; the script then replays the runs through the direct driver
and asserts the same block comes out, so the recorded runs are sufficient.

The metrics a case consulted are captured the same way: the resolver handed to
the reference wraps `advtext.style.fontlib_metrics` and notes every
`space_width`, `has` and `kern` it is asked.
"""

