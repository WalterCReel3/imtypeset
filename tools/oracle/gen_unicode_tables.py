"""
Write src/unicode_tables.h: the Python `str` predicates and general categories
the reference branches on, as range tables the port can look a codepoint up in.

Run with the reference's interpreter, so the Unicode version is the one the
goldens were dumped under (tests/golden/math/unicode.golden names it):

    PYTHONDONTWRITEBYTECODE=1 ../imgui-adv-text/.venv/bin/python -B \
        tools/oracle/gen_unicode_tables.py src/unicode_tables.h

The script refuses to write under any other Unicode version: a table from a
newer database would disagree with the goldens, and the difference would then
be the version and not the port.

tests/test_style.cpp compares every table with unicode.golden over every
codepoint, so a hand edit of the header, or a stale one, fails there.
"""

from __future__ import annotations

import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path

UNICODE_VERSION = "14.0.0"

PREDICATES: tuple[tuple[str, str, Callable[[str], bool]], ...] = (
    ("ISSPACE", "str.isspace()", str.isspace),
    ("ISPRINTABLE", "str.isprintable()", str.isprintable),
    ("ISALNUM", "str.isalnum()", str.isalnum),
    ("ISALPHA", "str.isalpha()", str.isalpha),
    ("ISUPPER", "str.isupper()", str.isupper),
    ("CATEGORY_CC", "general category Cc", lambda c: unicodedata.category(c) == "Cc"),
    ("CATEGORY_CF", "general category Cf", lambda c: unicodedata.category(c) == "Cf"),
    ("CATEGORY_MN", "general category Mn", lambda c: unicodedata.category(c) == "Mn"),
    ("CATEGORY_ME", "general category Me", lambda c: unicodedata.category(c) == "Me"),
)

HEADER = """\
// GENERATED by tools/oracle/gen_unicode_tables.py from Python's unicodedata.
// Do not edit: run the script again. Unicode {version}.
//
// These ranges are derived from the Unicode Character Database, which is
// copyright Unicode, Inc. and distributed under the Unicode License
// (https://www.unicode.org/license.txt). The licence's notice is to accompany
// copies of the data; THIRD-PARTY.md is where this tree keeps such notices.
//
// What the reference asks Python about a character, as tables: the `str`
// predicates on a one-character string and four general categories. Each table
// is the inclusive codepoint ranges where the predicate is TRUE, ascending and
// disjoint. tests/golden/math/unicode.golden holds the same ranges as the
// reference's interpreter reports them, and tests/test_style.cpp compares the
// two over every codepoint.
//
// Python's predicates are not the C library's and not ImGui's: U+00A0 and
// U+0085 are white space, U+01C5 is not upper case, and so on. Nothing in the
// port asks <cctype> about text.

#pragma once

// The tables are laid out by the generator.
// clang-format off

#include <cstddef>
#include <cstdint>

namespace ImTypeset::detail
{{

struct UnicodeRange {{
    uint32_t first;
    uint32_t last; // inclusive
}};

// Whether a sorted, disjoint table of ranges contains a codepoint.
inline bool unicode_in(const UnicodeRange* ranges, size_t count, uint32_t codepoint)
{{
    size_t low = 0;
    size_t high = count;
    while (low < high) {{
        const size_t middle = low + (high - low) / 2;
        if (codepoint > ranges[middle].last)
            low = middle + 1;
        else
            high = middle;
    }}
    return low < count && codepoint >= ranges[low].first;
}}

template <size_t N>
inline bool unicode_in(const UnicodeRange (&ranges)[N], uint32_t codepoint)
{{
    return unicode_in(ranges, N, codepoint);
}}
"""

FOOTER = """
// Python's str.isspace(), with the ASCII answer taken without a search.
inline bool py_isspace(uint32_t codepoint)
{
    if (codepoint < 0x80)
        return (codepoint >= 9 && codepoint <= 13) || (codepoint >= 28 && codepoint <= 32);
    return unicode_in(UNICODE_ISSPACE, codepoint);
}

// Python's str.isupper() on one character.
inline bool py_isupper(uint32_t codepoint)
{
    if (codepoint < 0x80)
        return codepoint >= 'A' && codepoint <= 'Z';
    return unicode_in(UNICODE_ISUPPER, codepoint);
}

inline bool py_isprintable(uint32_t codepoint)
{
    return unicode_in(UNICODE_ISPRINTABLE, codepoint);
}

inline bool py_isalnum(uint32_t codepoint)
{
    return unicode_in(UNICODE_ISALNUM, codepoint);
}

inline bool py_isalpha(uint32_t codepoint)
{
    return unicode_in(UNICODE_ISALPHA, codepoint);
}

} // namespace ImTypeset::detail
"""


def ranges_of(predicate: Callable[[str], bool]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start is None:
                start = codepoint
        elif start is not None:
            out.append((start, codepoint - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def render() -> str:
    parts = [HEADER.format(version=unicodedata.unidata_version)]
    for name, what, predicate in PREDICATES:
        ranges = ranges_of(predicate)
        parts.append(f"\n// {what}: {len(ranges)} ranges.\n")
        parts.append(f"inline constexpr UnicodeRange UNICODE_{name}[] = {{\n")
        line = "   "
        for first, last in ranges:
            item = f" {{0x{first:04X}, 0x{last:04X}}},"
            if len(line) + len(item) > 100:
                parts.append(line + "\n")
                line = "   "
            line += item
        parts.append(line + "\n};\n")
    parts.append(FOOTER)
    return "".join(parts)


def main() -> int:
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"this interpreter carries Unicode {unicodedata.unidata_version}; "
            f"the goldens were dumped under {UNICODE_VERSION}",
            file=sys.stderr,
        )
        return 1
    if len(sys.argv) != 2:
        print("usage: gen_unicode_tables.py <output header>", file=sys.stderr)
        return 2
    Path(sys.argv[1]).write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
