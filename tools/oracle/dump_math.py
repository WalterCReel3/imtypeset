SLUGS: dict[type, str] = {
    M.DelimiterTooSmallError: "delimiter-too-small",
    M.MissingGlyphError: "missing-glyph",
    M.TextFaceUnavailableError: "text-face-unavailable",
    NotImplementedError: "not-implemented",
    TypeError: "malformed-field",
}


@dataclass(frozen=True)
class Outcome:
    """
    What `mlist_to_hlist`, `hpack` and `ship` made of one math list.
    """

    nodes: list[Node] | None = None
    packed: PackResult | None = None
    cmds: list[Any] | None = None
    slug: str = ""
    detail: tuple[Any, ...] = ()
    message: str = ""


def convert(items: Sequence[MathItem], style: Style, fonts: MathFonts) -> Outcome:
    try:
        nodes = mlist_to_hlist(list(items), style, fonts)
        packed = hpack(nodes, measure=fonts.measure)
    except M.DelimiterTooSmallError as error:
        return Outcome(slug=SLUGS[type(error)], detail=(error.codepoint, error.needed, error.largest), message=str(error))
    except M.MissingGlyphError as error:
        return Outcome(slug=SLUGS[type(error)], detail=(ord(error.character), q(error.face.value)), message=str(error))
    except (M.TextFaceUnavailableError, NotImplementedError, TypeError) as error:
        return Outcome(slug=SLUGS[type(error)], message=str(error))
    cmds = ship(packed.box, Point(0, packed.box.height), measure=fonts.measure)
    return Outcome(nodes=nodes, packed=packed, cmds=cmds)


def mlist_case(
    w: Writer,
    name: str,
    items: Sequence[MathItem],
    style: Style,
    *,
    math: str = "real",
    text: str = "real",
    base_size: Scaled,
    shortfall: Scaled | None = None,
    source: tuple[str, bool] | None = None,
) -> Outcome:
    """
    One math list at one style and size: inputs, the questions asked, the answer.
    """
    saved = M.DELIMITER_SHORTFALL
    if shortfall is not None:
        M.DELIMITER_SHORTFALL = shortfall
    try:
        fonts, rows = recorded_fonts(math, text, base_size)
        outcome = convert(items, style, fonts)
        w.case(name, "mlist")
        if source is not None:
            w.r("source", q(source[0]), source[1])
        w.r("fonts", math, text, base_size)
        w.r("delimiter_shortfall", M.DELIMITER_SHORTFALL)
        w.r("style", style)
        emit_mlist(w, items)
        w.r(
            "sizes",
            *[v for size in MathSize for v in (fonts.sizes[size], q(fonts.keys[size]))],
        )
        if outcome.nodes is None:
            emit_questions(w, rows)
            w.r("refused", outcome.slug, *outcome.detail)
            w.r("message", q(outcome.message))
            if source is not None:
                done = typeset(source[0], base_size, display=source[1], fonts=fonts)
                assert isinstance(done, Refusal), (name, done)
                w.r("typeset_refusal", done.kind.value, done.position, utf8_offset(source[0], done.position), q(done.reason))
        else:
            assert outcome.packed is not None and outcome.cmds is not None
            # Asked for after the conversion, so the measure's own questions are
            # recorded too; a set formula never raises here.
            emit_measure(w, fonts.measure, outcome.nodes)
            emit_questions(w, rows)
            emit_nodes(w, "hlist", outcome.nodes)
            emit_packed(w, outcome.packed)
            w.r("origin", 0, outcome.packed.box.height)
            emit_cmds(w, outcome.cmds)
            if source is not None:
                done = typeset(source[0], base_size, display=source[1], fonts=fonts)
                assert not isinstance(done, Refusal) and done.box == outcome.packed.box, name
        w.end()
        return outcome
    finally:
        M.DELIMITER_SHORTFALL = saved


