def verify_table(records: Records, params: dict[str, tuple[float, ...]]) -> int:
    """
    A `table` case: every record whose answer is one call away is called again.
    """
    checks = 0
    while records.peek()[0] != "endcase":
        row = records.take()
        tag = row[0]
        if tag == "params":
            params[unq(row[1])] = tuple(float.fromhex(v) for v in row[2:])
            assert len(row) == 2 + len(PARAM_FIELDS)
        elif tag == "font_key":
            assert font_key(Face(unq(row[1])), int(row[2])) == unq(row[3])
        elif tag == "parse_font_key":
            try:
                spec = parse_font_key(unq(row[1]))
            except ValueError:
                assert row[2] == "error"
            else:
                assert row[2:] == ["ok", q(spec.face.value), str(spec.size)]
        elif tag == "style":
            style = Style[row[1].upper()]
            expected = (
                int(style),
                A.cramped_style(style),
                A.sup_style(style),
                A.sub_style(style),
                A.num_style(style),
                A.denom_style(style),
                A.size_for(style),
                A.is_display(style),
                A.is_cramped(style),
            )
            assert row[2:] == [tok(v) for v in expected]
        elif tag == "half":
            assert M._half(int(row[1])) == int(row[2])
        elif tag == "from_mu":
            spec = M._from_mu(MuGlue(int(row[1]), int(row[2]), int(row[3])), int(row[4]))
            assert [spec.width, spec.stretch, spec.shrink] == [int(v) for v in row[5:8]]
        elif tag == "space_factor_after":
            assert space_factor_after(chr(int(row[1])), int(row[2])) == int(row[3])
        elif tag == "interword_glue":
            spec = interword_glue(int(row[1]), int(row[2]), Spacing[row[3].upper()])
            assert [spec.width, spec.stretch, spec.shrink] == [int(v) for v in row[4:7]]
        elif tag == "strut_filling":
            strut = Strut.filling(int(row[1]))
            assert [strut.height, strut.depth] == [int(v) for v in row[2:4]]
        elif tag == "measure":
            dimens = char_measure(fontlib_metrics)(CharNode(unq(row[1]), int(row[2])))
            assert [dimens.width, dimens.height, dimens.depth] == [int(v) for v in row[3:6]]
        elif tag == "kern":
            assert fontlib_metrics(unq(row[1])).kern(int(row[2]), int(row[3])) == float.fromhex(row[4])
        elif tag == "mu":
            fonts = math_fonts(int(row[1]), _real_math)
            assert fonts.mu(Style[row[2].upper()]) == int(row[3])
        else:
            continue
        checks += 1
    return checks


def verify(path: Path) -> tuple[int, int]:
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    assert text.endswith("\n") and "\r" not in text and "\t" not in text
    for line in text.split("\n"):
        assert not line.startswith(" ") and not line.endswith(" ") and "  " not in line, line
    records = Records(text)
    header = records.take("golden")
    assert int(header[1]) == FORMAT_VERSION and unq(header[2]) == "math/" + path.stem
    cases = checks = 0
    names: set[str] = set()
    params: dict[str, tuple[float, ...]] = {}
    while not records.done():
        row = records.peek()
        assert row[0] == "case", row
        assert row[1] not in names, row[1]
        names.add(row[1])
        kind = row[2]
        if kind == "ranges":
            checks += verify_unicode(records)
            cases += 1
            continue
        records.take("case")
        if kind == "parse":
            checks += verify_parse(records)
        elif kind == "mlist":
            checks += verify_mlist(records, params)
        elif kind == "inline":
            checks += verify_inline(records)
        elif kind == "linebreak":
            checks += core.verify_case(records, kind)
        else:
            assert kind == "table", kind
            checks += verify_table(records, params)
        records.take("endcase")
        cases += 1
    return cases, checks


