class Recording:
    """
    One metrics object, with every question it is asked noted down.

    Not a subclass and not a Protocol implementation by inheritance: the
    reference only ever calls these names.
    """

    def __init__(self, inner: Any, key: str, rows: set[tuple[Any, ...]]) -> None:
        self._inner = inner
        self._key = key
        self._rows = rows

    @property
    def face(self) -> Face:
        return self._inner.face  # type: ignore[no-any-return]

    @property
    def size(self) -> float:
        return self._inner.size  # type: ignore[no-any-return]

    @property
    def em(self) -> float:
        return self._inner.em  # type: ignore[no-any-return]

    @property
    def ascent(self) -> float:
        return self._inner.ascent  # type: ignore[no-any-return]

    @property
    def descent(self) -> float:
        return self._inner.descent  # type: ignore[no-any-return]

    @property
    def x_height(self) -> float:
        return self._inner.x_height  # type: ignore[no-any-return]

    @property
    def space_width(self) -> float:
        value = float(self._inner.space_width)
        self._rows.add(("q_space", self._key, value))
        return value

    @property
    def math(self) -> MathParams:
        params: MathParams = self._inner.math
        self._rows.add(("q_params", self._key, *[float(getattr(params, n)) for n in PARAM_FIELDS]))
        return params

    def has(self, codepoint: int) -> bool:
        value = bool(self._inner.has(codepoint))
        self._rows.add(("q_has", self._key, codepoint, value))
        return value

    def advance(self, codepoint: int) -> float:
        value = float(self._inner.advance(codepoint))
        self._rows.add(("q_advance", self._key, codepoint, value))
        return value

    def bbox(self, codepoint: int) -> GlyphBBox:
        box: GlyphBBox = self._inner.bbox(codepoint)
        self._rows.add(
            ("q_bbox", self._key, codepoint, float(box.x_min), float(box.y_min), float(box.x_max), float(box.y_max))
        )
        return box

    def kern(self, codepoint: int, following: int) -> float:
        value = float(self._inner.kern(codepoint, following))
        self._rows.add(("q_kern", self._key, codepoint, following, value))
        return value

    def italic_correction(self, codepoint: int) -> float:
        value = float(self._inner.italic_correction(codepoint))
        self._rows.add(("q_italic", self._key, codepoint, value))
        return value

    def vertical_variants(self, codepoint: int) -> tuple[GlyphVariant, ...]:
        chain: tuple[GlyphVariant, ...] = tuple(self._inner.vertical_variants(codepoint))
        flat: list[Any] = []
        for variant in chain:
            flat.extend((q(variant.name), variant.codepoint, float(variant.extent)))
        self._rows.add(("q_variants", self._key, codepoint, len(chain), *flat))
        return chain


