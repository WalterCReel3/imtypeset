class Writer(core.Writer):
    """
    dump_core's writer, with this script's header and file id.
    """

    def __init__(self, name: str, about: str) -> None:
        super().__init__(name, about)
        self.lines = [
            "# Generated by tools/oracle/dump_math.py from the Python reference. Do not edit.",
            "# Record vocabulary: tools/oracle/FORMAT-math.md, over tools/oracle/FORMAT.md.",
            *[f"# {line}" for line in about.strip().splitlines()],
            f"golden {FORMAT_VERSION} {q('math/' + name)}",
        ]
        # Math parameters by font key, as the cases of this file were told
        # them. Written once, as the file's first case, by `finish`.
        self.params: dict[str, tuple[float, ...]] = {}

    def finish(self) -> None:
        """
        Put the `font-params` case, if any case asked for parameters, first.
        """
        if not self.params:
            return
        assert "font-params" not in self.names
        head = next(i for i, line in enumerate(self.lines) if line.startswith("golden ")) + 1
        table = [f"case {q('font-params')} table"]
        for key in sorted(self.params):
            table.append(" ".join(tok(v) for v in ("params", q(key), *self.params[key])))
        table.append("endcase")
        self.lines[head:head] = table
        self.names.add("font-params")
        self.cases += 1


def utf8_offset(source: str, position: int) -> int:
    """
    A codepoint offset into `source` as a byte offset into its UTF-8 encoding.
    """
    return len(source[:position].encode("utf-8"))


def encodable(text: str) -> bool:
    """
    Whether a Python string is valid Unicode text (it can hold lone surrogates).
    """
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        return False
    return True


