def parse_case(w: Writer, name: str, source: str) -> Formula | Refusal:
    result = parse(source)
    shown = parse(source, display=True)
    w.case(name, "parse")
    w.r("source", q(source))
    if isinstance(result, Refusal):
        assert isinstance(shown, Refusal) and replace(shown, display=False) == result
        w.r("refusal", result.kind.value, result.position, utf8_offset(source, result.position), q(result.reason))
    else:
        assert isinstance(shown, Formula) and shown.items == result.items
        assert result.style is Style.TEXT and shown.style is Style.DISPLAY
        w.r("formula")
        emit_mlist(w, result.items)
    w.end()
    return result


def dump_mathtext() -> Writer:
    w = Writer(
        "mathtext",
        """
advtext.mathtext.parse over a corpus: every command it accepts and every one it
refuses by name, every character with a class, the reference's own test and
demo sources, and deterministic fuzz. Each case is a source and either the math
list it parses to or the refusal (kind, position, reason). `display` does not
change either and is not recorded.
""",
    )

    w.case("tables", "table")
    for name in T.supported_commands():
        w.r("supported", q(name))
    for name, kind in T.refused_commands().items():
        w.r("refused_command", q(name), kind.value, q(T._REFUSED[name][1]))
    for written, codepoint in sorted(T.sized_delimiters().items()):
        w.r("sized_delimiter", q(written), -1 if codepoint is None else codepoint)
    for kind in T.RefusalKind:
        w.r("refusal_kind", kind.value)
    for name in sorted(T._PROSE):
        w.r("prose_command", q(name), q(T._PROSE[name].value))
    w.r("const", "max_depth", "int", T.MAX_DEPTH)
    w.end()

    index = 0

    def add(prefix: str, source: str) -> None:
        nonlocal index
        if not encodable(source):
            return
        index += 1
        parse_case(w, f"{prefix}#{index}", source)

    for what, source in page.REFERENCE:
        add("page-reference/" + what, source)
    for what, source in page.REFUSED:
        add("page-refused/" + what, source)
    for key, sources in GALLERY_SOURCES:
        for source in sources:
            add("gallery/" + key, source)
    for source, _display in demo_formulas():
        add("demo", source)
    for source in ACCEPTED_SOURCES:
        add("accepted", source)
    for source in REFUSED_SOURCES:
        add("refused", source)
    for label, source in command_sources():
        add("command/" + label, source)
    for label, source in character_sources():
        add("character/" + label, source)

    rng = Rng(20261009)
    for _ in range(1500):
        add("soup", "".join(rng.pick(FUZZ_PIECES) for _ in range(rng.below(14))))
    for _ in range(300):
        add("grown", grown(rng, rng.between(1, 6)))
    for _ in range(400):
        add("characters", "".join(chr(rng.below(0x3000)) for _ in range(rng.below(12))))
    for _ in range(200):
        words = "".join(chr(rng.below(0x3000)) for _ in range(rng.below(12))).replace("}", "")
        add("words", "\\text{" + words + "}")

    # Last, so that the running number in every name above stays what it was.
    for source in BRACED_SOURCES:
        add("braced", source)
    alone = parse("{x_2}")
    assert isinstance(alone, Formula) and len(alone.items) == 1
    kept = alone.items[0]
    # The group survives as a sub-list, and the script stays inside it.
    assert isinstance(kept, Atom) and kept.sub is None and isinstance(kept.nucleus, SubList)
    inside = kept.nucleus.items[0]
    assert isinstance(inside, Atom) and inside.sub is not None
    twice = parse("{{x}}_1")
    assert isinstance(twice, Formula) and isinstance(twice.items[0], Atom)
    assert isinstance(twice.items[0].nucleus, MathChar) and twice.items[0].sub is not None
    return w


def verify_parse(records: Records) -> int:
    source = unq(records.take("source")[1])
    row = records.take()
    if row[0] == "refusal":
        result = parse(source)
        assert isinstance(result, Refusal), source
        assert (result.kind.value, result.position, result.reason) == (row[1], int(row[2]), unq(row[4])), source
        assert utf8_offset(source, result.position) == int(row[3])
    else:
        assert row[0] == "formula"
        items = read_mlist(records)
        result = parse(source)
        assert isinstance(result, Formula) and result.items == items, source
    return 1


