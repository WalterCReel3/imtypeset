def dump_formulas() -> Writer:
    w = Writer(
        "formulas",
        """
Sources through the whole of advtext.mathtext: parse, then mlist_to_hlist, hpack
and ship on the real fonts (Latin Modern Math; the prose faces for \\text). Each
case carries the source, the math list it parsed to, the style and size, and
either the hlist, box and draw commands or the engine's refusal together with
the Refusal `typeset` makes of it. Sources `parse` refuses are in
mathtext.golden and are not repeated here.
""",
    )
    body = sp_from_px(16.0)
    index = 0

    def add(prefix: str, source: str, *, displays: Iterable[bool] = (False, True), sizes: Iterable[Scaled] = (body,)) -> None:
        nonlocal index
        if not encodable(source):
            return
        result = parse(source)
        if isinstance(result, Refusal):
            return
        for size in sizes:
            for display in displays:
                index += 1
                style = Style.DISPLAY if display else Style.TEXT
                mlist_case(w, f"{prefix}#{index}", result.items, style, base_size=size, source=(source, display))

    several = (sp_from_px(10.0), sp_from_px(13.0), body, sp_from_px(17.5), sp_from_px(34.0, 96.0))
    for what, source in page.REFERENCE:
        add("page-reference/" + what, source, sizes=several)
