def emit_field(w: Writer, field: Field) -> None:
    if field is None:
        w.r("empty")
    elif isinstance(field, MathChar):
        w.r("mathchar", field.codepoint)
    elif isinstance(field, SubBox):
        w.r("subbox")
        emit_node(w, field.box)
    elif isinstance(field, SubList):
        w.r("sublist", len(field.items))
        for item in field.items:
            emit_item(w, item)
        w.r("endsublist")
    elif isinstance(field, MathText):
        w.r("mathtext", q(field.face.value), q(field.text))
    elif isinstance(field, MuGlue):
        w.r("muglue", field.width, field.stretch, field.shrink)
    else:
        raise TypeError(type(field))


def emit_item(w: Writer, item: MathItem) -> None:
    if isinstance(item, Atom):
        w.r("atom", item.kind, item.limits)
        emit_field(w, item.nucleus)
        emit_field(w, item.sup)
        emit_field(w, item.sub)
    elif isinstance(item, Fraction):
        w.r("fraction", item.thickness is not None, item.thickness or 0)
        emit_field(w, item.numerator)
        emit_field(w, item.denominator)
    else:
        raise TypeError(type(item))


def emit_mlist(w: Writer, items: Sequence[MathItem]) -> None:
    w.r("mlist", len(items))
    for item in items:
        emit_item(w, item)
    w.r("endmlist")


def read_field(records: Records) -> Field:
    row = records.take()
    tag = row[0]
    if tag == "empty":
        return None
    if tag == "mathchar":
        return MathChar(int(row[1]))
    if tag == "subbox":
        box = read_node(records)
        assert isinstance(box, Box)
        return SubBox(box)
    if tag == "sublist":
        items = tuple(read_item(records) for _ in range(int(row[1])))
        records.take("endsublist")
        return SubList(items)
    if tag == "mathtext":
        return MathText(unq(row[2]), Face(unq(row[1])))
    if tag == "muglue":
        return MuGlue(int(row[1]), int(row[2]), int(row[3]))
    raise AssertionError(f"not a field record: {row}")


def read_item(records: Records) -> MathItem:
    row = records.take()
    if row[0] == "atom":
        kind = AtomType[row[1].upper()]
        limits = Limits[row[2].upper()]
        nucleus = read_field(records)
        sup = read_field(records)
        sub = read_field(records)
        return Atom(kind, nucleus, sup, sub, limits)
    if row[0] == "fraction":
        thickness = int(row[2]) if row[1] == "1" else None
        numerator = read_field(records)
        denominator = read_field(records)
        return Fraction(numerator, denominator, thickness)
    raise AssertionError(f"not a math item record: {row}")


def read_mlist(records: Records) -> tuple[MathItem, ...]:
    row = records.take("mlist")
    items = tuple(read_item(records) for _ in range(int(row[1])))
    records.take("endmlist")
    return items


