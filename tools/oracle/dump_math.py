def _broken_prose(key: str) -> Any:
    raise fontlib.MissingFontError(f"no file for {key}")


MATH_PROVIDERS: dict[str, Callable[[Scaled], Any]] = {
    "real": _real_math,
    "fake": _fake_math,
    "chained": _chained_math,
}
TEXT_PROVIDERS: dict[str, Callable[[str], Any] | None] = {
    "none": None,
    "real": fontlib_metrics,
    "fake": _fake_prose,
    "broken": _broken_prose,
}


def recorded_fonts(math: str, text: str, base_size: Scaled) -> tuple[MathFonts, set[tuple[Any, ...]]]:
    """
    `math_fonts` over the named providers, each wrapped in a `Recording`.
    """
    rows: set[tuple[Any, ...]] = set()
    math_provider = MATH_PROVIDERS[math]
    text_provider = TEXT_PROVIDERS[text]

    def resolve(size: Scaled) -> Any:
        return Recording(math_provider(size), font_key(Face.MATH, size), rows)

    def resolve_text(key: str) -> Any:
        assert text_provider is not None
        return Recording(text_provider(key), key, rows)

    fonts = math_fonts(base_size, resolve, text=None if text_provider is None else resolve_text)
    return fonts, rows


def emit_questions(w: Writer, rows: set[tuple[Any, ...]]) -> None:
    for row in sorted(rows, key=lambda r: (r[0], r[1], r[2:])):
        if row[0] == "q_params":
            # The 27 values are the same for a key wherever it is asked; they
            # are in the file's `font-params` case.
            assert w.params.setdefault(row[1], row[2:]) == row[2:]
            w.r(row[0], q(row[1]))
        else:
            w.r(row[0], q(row[1]), *row[2:])


