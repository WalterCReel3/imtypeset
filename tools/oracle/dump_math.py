def true_ranges(predicate: Callable[[str], bool]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = -1
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start < 0:
                start = codepoint
        elif start >= 0:
            ranges.append((start, codepoint - 1))
            start = -1
    if start >= 0:
        ranges.append((start, 0x10FFFF))
    return ranges


def dump_unicode() -> Writer:
    w = Writer(
        "unicode",
        f"""
The Python str predicates the reference's parsers branch on, over every
codepoint 0..0x10FFFF, as inclusive ranges where the predicate is TRUE. The
port has no Python and needs a table for each; these are the tables to test
against. Unicode {unicodedata.unidata_version} (this interpreter's unicodedata).
These ranges are derived from the Unicode Character Database, which is
copyright Unicode, Inc. and distributed under the Unicode License
(https://www.unicode.org/license.txt). The licence's notice is to accompany
copies of the data; THIRD-PARTY.md is where this tree keeps such notices.
""",
    )
    w.case("predicates", "ranges")
    w.r("unicode_version", q(unicodedata.unidata_version))
    for name, predicate in PREDICATES:
        ranges = true_ranges(predicate)
        w.r("predicate", name, len(ranges), sum(last - first + 1 for first, last in ranges))
        for first, last in ranges:
            w.r("range", first, last)
    w.end()
    return w


def verify_unicode(records: Records) -> int:
    checks = 0
    records.take("case")
    assert unq(records.take("unicode_version")[1]) == unicodedata.unidata_version
    by_name = dict(PREDICATES)
    while records.peek()[0] == "predicate":
        row = records.take()
        predicate = by_name[row[1]]
        member = bytearray(0x110000)
        for _ in range(int(row[2])):
            first, last = (int(v) for v in records.take("range")[1:3])
            for codepoint in range(first, last + 1):
                member[codepoint] = 1
        assert sum(member) == int(row[3])
        for codepoint in range(0x110000):
            assert bool(member[codepoint]) == predicate(chr(codepoint)), (row[1], codepoint)
        checks += 1
    records.take("endcase")
    return checks


