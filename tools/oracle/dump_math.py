#!/usr/bin/env python3
"""
Dump math goldens from the Python reference (imgui-adv-text).

Writes tests/golden/math/*.golden: the style subset, the Unicode predicates the
reference leans on, `advtext.mathtext.parse` over a corpus of accepted and
refused sources, `advtext.math.mlist_to_hlist` over hand-built and parsed math
lists, and paragraphs with formulas in them. The record vocabulary is specified
in tools/oracle/FORMAT-math.md, on top of the shared records of FORMAT.md.

Run from the imtypeset repository root, with the reference's interpreter:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=../imgui-adv-text \\
        ../imgui-adv-text/.venv/bin/python -B tools/oracle/dump_math.py

    ... dump_math.py --verify   re-reads every golden with a reader written
                                from the two FORMAT documents, rebuilds the
                                inputs from the records, replays them through
                                the reference and compares.

The script only reads the reference. Output is deterministic: no clock, no
`random`, no hash-ordered iteration reaches a file, so a second run is
byte-identical to the first.

The shared records (nodes, draw commands, measures, the `linebreak` case) are
written by the functions of the sibling script dump_core.py, imported here, so
they cannot drift from what FORMAT.md describes.

Every font question the reference asks while converting a math list is
recorded and written beside the case (`q_*` records), so a port can be driven
from those answers alone, with no font reader, or from its own reader with the
answers as a cross-check.
"""

