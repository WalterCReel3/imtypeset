def inline_children(source: str) -> list[Any] | None:
    """
    markdown-it's inline tokens for a one-paragraph source, or `None` if the
    source is not one paragraph of text and formulas and nothing else.
    """
    tokens = markdown._tokens(source, math=True)
    if [token.type for token in tokens] != ["paragraph_open", "inline", "paragraph_close"]:
        return None
    children = list(tokens[1].children or [])
    if any(child.type not in ("text", "math_inline") for child in children):
        return None
    return children


def dump_inline() -> Writer:
    w = Writer(
        "inline",
        """
Formulas in running text, through advtext.markdown.build_document with
math=advtext.mathtext.markdown_math(): where the reference finds `$...$` in a
paragraph (an `inline` case: the segments, and the formula spans with their
outcome), and the paragraph that results, broken at several widths (a
`linebreak` case, FORMAT.md section 6, named `<same name>/paragraph`). Sources
are plain text and dollars only: nothing else markdown would interpret, since
the port has no markdown.
""",
    )
    theme = Theme.build()
    measure = char_measure(fontlib_metrics)
    builder = markdown_math()

    def paragraph(name: str, source: str, widths: Sequence[float]) -> None:
        document = markdown.build_document(source, theme, fontlib_metrics, math=builder)
        blocks = [block for block in document.blocks if isinstance(block, markdown.TextBlock)]
        assert len(blocks) == len(document.blocks) == 1, (source, document)
        (block,) = blocks
        w.case(name, "inline")
        w.r("source", q(source))
        tokens = markdown._tokens(source, math=True)
        children = inline_children(source)
        if children is not None:
            w.r("segments", len(children))
            for child in children:
                if child.type == "text":
                    w.r("text", q(child.content))
                else:
                    w.r("formula", child.markup == "$$", q(child.content))
        else:
            # A `$$` block: the whole source is one display formula.
            (token,) = tokens
            assert token.type == "math_block", (source, token.type)
            w.r("block", bool((token.meta or {}).get("closed", True)), q(str(token.content)))
        w.r("spans", len(block.formulas))
        for span in block.formulas:
            w.r(
                "span",
                q(span.source),
                span.display,
                span.unclosed,
                span.start,
                span.end,
                bool(span.refusal),
                span.position,
                utf8_offset(span.source, span.position),
                q(span.refusal),
            )
        w.end()
        core.paragraph_case(w, name + "/paragraph", "markdown-math", source, block, theme, widths, measure)

    for number, source in enumerate(INLINE_SOURCES, 1):
        assert inline_children(source) is not None, source
        long = len(source) > 60
        paragraph(f"inline#{number}", source, (160.0, 300.0, 520.0) if long else (300.0,))
    for number, source in enumerate(DISPLAY_SOURCES, 1):
        paragraph(f"display#{number}", source, (160.0, 520.0))
    return w


def verify_inline(records: Records) -> int:
    source = unq(records.take("source")[1])
    theme = Theme.build()
    document = markdown.build_document(source, theme, fontlib_metrics, math=markdown_math())
    (block,) = document.blocks
    assert isinstance(block, markdown.TextBlock)
    children = inline_children(source)
    if records.peek()[0] == "segments":
        count = int(records.take("segments")[1])
        assert children is not None and count == len(children)
        for child in children:
            row = records.take()
            if row[0] == "text":
                assert child.type == "text" and child.content == unq(row[1])
            else:
                assert row[0] == "formula" and child.type == "math_inline"
                assert (child.markup == "$$") == (row[1] == "1") and child.content == unq(row[2])
    else:
        row = records.take("block")
        (token,) = markdown._tokens(source, math=True)
        assert children is None and token.type == "math_block"
        assert (row[1] == "1") == bool((token.meta or {}).get("closed", True)) and unq(row[2]) == str(token.content)
    count = int(records.take("spans")[1])
    assert count == len(block.formulas)
    for span in block.formulas:
        row = records.take("span")
        assert (unq(row[1]), row[2] == "1", row[3] == "1") == (span.source, span.display, span.unclosed)
        assert (int(row[4]), int(row[5])) == (span.start, span.end)
        assert (row[6] == "1", int(row[7]), unq(row[9])) == (bool(span.refusal), span.position, span.refusal)
    return 1


