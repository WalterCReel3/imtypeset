#!/usr/bin/env python3
"""
Dump a golden of the reference's FONT SPECIMEN (imgui-adv-text,
`advtext.ui.specimen.build_specimen`): the set width of one line in each face,
of one face up the size ladder, and of each kerned pair set with and without
its kern -- every length as the integer scaled points the reference computed.

The product's demo shows the same chart (src/imtypeset_demo.cpp, "Specimen").
A check of it against numbers read off the reference's docstring, to four
decimals of a pixel, cannot see a scaled point: one is about 2e-5 px. This
file is what an exact check reads instead.

Run from the imtypeset repository root, with the reference's interpreter:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=build/advtext-reference \\
        ../imgui-adv-text/.venv/bin/python -P -B tools/oracle/dump_specimen.py

    ... dump_specimen.py --check    dump again in memory and compare with the
                                    file, byte for byte; writes nothing
    ... dump_specimen.py --verify   re-read the file with a reader that uses
                                    only what FORMAT-specimen.md says and
                                    check every sum it states; asks the
                                    reference nothing and writes nothing

Writes tests/golden/specimen/specimen.golden. The record vocabulary is
tools/oracle/FORMAT-specimen.md.

Nothing is written into the reference: Python is run with -B, and the
reference is only imported and called.

What the script asserts while it dumps (a failure writes nothing): no face is
absent; each `row`'s set width is the width of the sample the script sets
again with the reference's `_set`; a pair's `kerned` is `unkerned + kern`, and
`unkerned` is the sum of its two letters set alone; a sample's width is the
sum of its characters, kerns and glue.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pinned_reference  # noqa: E402

pinned_reference.require()

import dump_core as core  # noqa: E402
from dump_core import q, unq  # noqa: E402

from advtext import fontlib  # noqa: E402
from advtext.fontmetrics import Face  # noqa: E402
from advtext.nodes import Box, CharNode, Glue, Kern  # noqa: E402
from advtext.pack import CharMeasure  # noqa: E402
from advtext.style import BODY_SIZE_PX, TYPE_SCALE_RATIO, Theme, char_measure, font_key, fontlib_metrics  # noqa: E402
from advtext.ui import specimen as S  # noqa: E402
from advtext.units import sp_from_px  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "tests" / "golden" / "specimen"
NAME = "specimen"
FORMAT_VERSION = 1

# Patches applied to the reference in memory before dumping (D32.3). None.
REFERENCE_PATCHES: tuple[str, ...] = ()

# The measure the reference's own tests build the specimen at
# (tests/test_specimen.py). It is the width the three notes are broken to and
# no row depends on it.
MEASURE_PX = 760.0

ABOUT = """
The reference's font specimen: the set width of one line in each face, of one
face up the size ladder, and of each kerned pair with and without its kern,
in integer scaled points.
"""


class Writer(core.Writer):
    def __init__(self, name: str, about: str) -> None:
        super().__init__(name, about)
        self.lines = [
            "# Generated by tools/oracle/dump_specimen.py from the Python reference. Do not edit.",
            "# Record vocabulary: tools/oracle/FORMAT-specimen.md.",
            *[f"# {line}" for line in pinned_reference.header_lines()],
            *[f"# {line}" for line in about.strip().splitlines()],
            f"golden {FORMAT_VERSION} {q('specimen/' + name)}",
        ]


def emit_box(w: Writer, tag: str, box: Box) -> None:
    w.r(tag, box.width, box.height, box.depth)


def emit_set(w: Writer, role: str, text: str, face: Face, size: int, kerned: bool, measure: CharMeasure) -> Box:
    """
    One call of the reference's `_set`, and what the box it returned holds.
    """
    metrics = fontlib_metrics(font_key(face, size))
    box = S._set(text, face, size, metrics, measure, kerned=kerned)
    w.r("set", role, face, size, kerned, q(text), box.width, box.height, box.depth, len(box.contents))
    total = 0
    for node in box.contents:
        if isinstance(node, CharNode):
            dimens = measure(node)
            assert node.font == font_key(face, size)
            w.r("char", node.codepoint, dimens.width, dimens.height, dimens.depth)
            total += dimens.width
        elif isinstance(node, Kern):
            w.r("kern", node.width)
            total += node.width
        elif isinstance(node, Glue):
            w.r("glue", *core.spec_tokens(node.spec))
            total += node.spec.width
        else:
            raise TypeError(type(node))
    assert total == box.width, "a sample set at its natural width is the sum of what it holds"
    w.r("endset")
    return box


def dump() -> Writer:
    w = Writer(NAME, ABOUT)
    theme = Theme.build()
    measure_width = sp_from_px(MEASURE_PX, theme.px_per_inch)
    measure = char_measure(fontlib_metrics)
    w.case("reference", "specimen")

    # INPUT: what `build_specimen` was called with, and the constants of the
    # reference's module it reads.
    w.r("theme", float(theme.px_per_inch), float(BODY_SIZE_PX), float(TYPE_SCALE_RATIO))
    w.r("measure", float(MEASURE_PX), measure_width)
    w.r("specimen_px", float(S.SPECIMEN_PX), sp_from_px(S.SPECIMEN_PX, theme.px_per_inch))
    w.r("kern_px", float(S.KERN_PX), sp_from_px(S.KERN_PX, theme.px_per_inch))
    w.r("label_px", float(S.LABEL_PX), sp_from_px(S.LABEL_PX, theme.px_per_inch))
    ladder = S.ladder_sizes_px(BODY_SIZE_PX)
    w.r("ladder", len(ladder), *[float(size_px) for size_px in ladder])
    w.r("texts", q(S.PANGRAM), q(S.LADDER_TEXT))
    w.r("faces", len(S.FACE_LABELS))
    for face, label in S.FACE_LABELS.items():
        w.r("face", face, q(face.value), q(label), q(Path(fontlib.font_file(face)).name))
    w.r("pairs", len(S.KERN_PAIRS), *[q(left + right) for left, right in S.KERN_PAIRS])
    w.r("kern_face", S.KERN_FACE)

    w.r("expect")
    built = S.build_specimen(theme, measure_width, fontlib_metrics, measure=measure)
    assert not built.absent, "every face of the specimen resolves"
    assert [section.title for section in built.sections][:2] == ["The six faces", "A size ladder"]
    assert len(built.sections) == 3

    w.r("specimen", built.gutter, len(built.sections), len(built.absent), built.box.width, built.box.height,
        built.box.depth)  # fmt: skip
    samples = (S.PANGRAM, S.LADDER_TEXT, None)
    for section, text in zip(built.sections, samples, strict=True):
        w.r("section", q(section.title), len(section.rows), section.header is not None)
        emit_box(w, "sectionbox", section.box)
        emit_box(w, "notebox", section.note)
        if section.header is not None:
            emit_box(w, "headerbox", section.header)
        for row in section.rows:
            w.r("row", q(row.label), row.face, row.size, row.set_width, row.label_width, row.pair is not None)
            emit_box(w, "rowbox", row.box)
            if row.pair is None:
                assert text is not None
                again = emit_set(w, "sample", text, row.face, row.size, True, measure)
                assert again.width == row.set_width, "the row's set width is its sample's"
                continue
            pair = row.pair
            w.r("pair", q(pair.left), q(pair.right), pair.kern, pair.kerned, pair.unkerned)
            assert pair.kerned == pair.unkerned + pair.kern == row.set_width
            kerned = emit_set(w, "kerned", pair.left + pair.right, row.face, row.size, True, measure)
            plain = emit_set(w, "unkerned", pair.left + pair.right, row.face, row.size, False, measure)
            left = emit_set(w, "left", pair.left, row.face, row.size, True, measure)
            right = emit_set(w, "right", pair.right, row.face, row.size, True, measure)
            assert (kerned.width, plain.width) == (pair.kerned, pair.unkerned)
            assert left.width + right.width == pair.unkerned, "unkerned is the two letters set alone"
        w.r("endsection")
    w.end()
    return w


# --------------------------------------------------------------------------
# --verify: a reader written from FORMAT-specimen.md, with no reference
# --------------------------------------------------------------------------


def verify(text: str) -> list[str]:
    """
    Problems found re-reading `text` as FORMAT-specimen.md describes it.
    """
    problems: list[str] = []
    records = [line.split(" ") for line in text.splitlines() if line and not line.startswith("#")]
    position = 0

    def take(tag: str) -> list[str]:
        nonlocal position
        record = records[position]
        if record[0] != tag:
            raise ValueError(f"record {position}: expected `{tag}`, found `{record[0]}`")
        position += 1
        return record

    def peek() -> str:
        return records[position][0]

    def read_set(role: str) -> tuple[int, str, int]:
        found = take("set")
        if found[1] != role:
            raise ValueError(f"record {position}: expected set `{role}`, found `{found[1]}`")
        width, count = int(found[6]), int(found[9])
        total = 0
        for _ in range(count):
            tag = peek()
            node = take(tag)
            if tag == "char":
                total += int(node[2])
            elif tag in ("kern", "glue"):
                total += int(node[1])
            else:
                raise ValueError(f"record {position}: `{tag}` inside a set")
        take("endset")
        if total != width:
            problems.append(f"set {role} {found[5]}: holds {total}, says {width}")
        return width, unq(found[5]), int(found[3])

    try:
        header = take("golden")
        if header[1:] != [str(FORMAT_VERSION), "specimen/" + NAME]:
            problems.append(f"header {header}")
        take("case")
        take("theme")
        take("measure")
        sizes = {tag: int(take(tag)[2]) for tag in ("specimen_px", "kern_px", "label_px")}
        ladder = take("ladder")
        if len(ladder) != 2 + int(ladder[1]):
            problems.append("ladder count")
        texts = [unq(token) for token in take("texts")[1:]]
        faces = [take("face")[1] for _ in range(int(take("faces")[1]))]
        pairs = [unq(token) for token in take("pairs")[2:]]
        take("kern_face")
        take("expect")
        nsections = int(take("specimen")[2])
        expected_rows = [len(faces), int(ladder[1]), len(pairs)]
        for number in range(nsections):
            section = take("section")
            take("sectionbox")
            take("notebox")
            if section[3] == "1":
                take("headerbox")
            if int(section[2]) != expected_rows[number]:
                problems.append(f"section {number}: {section[2]} rows, expected {expected_rows[number]}")
            for index in range(int(section[2])):
                row = take("row")
                size, set_width = int(row[3]), int(row[4])
                take("rowbox")
                if row[6] == "0":
                    width, sample, at = read_set("sample")
                    if (width, sample, at) != (set_width, texts[number], size):
                        problems.append(f"row {unq(row[1])}: sample {sample!r} {width}@{at}, row says {set_width}@{size}")
                    if number == 0 and (row[2] != faces[index] or size != sizes["specimen_px"]):
                        problems.append(f"row {unq(row[1])}: face or size out of order")
                    continue
                pair = take("pair")
                kern, kerned, unkerned = int(pair[3]), int(pair[4]), int(pair[5])
                widths = {role: read_set(role)[0] for role in ("kerned", "unkerned", "left", "right")}
                if unq(pair[1]) + unq(pair[2]) != pairs[index] or size != sizes["kern_px"]:
                    problems.append(f"pair {index}: not {pairs[index]} at the kern size")
                if kerned != unkerned + kern or set_width != kerned:
                    problems.append(f"pair {pairs[index]}: kerned {kerned} != unkerned {unkerned} + kern {kern}")
                if (widths["kerned"], widths["unkerned"]) != (kerned, unkerned):
                    problems.append(f"pair {pairs[index]}: its sets disagree with it")
                if widths["left"] + widths["right"] != unkerned:
                    problems.append(f"pair {pairs[index]}: left + right != unkerned")
            take("endsection")
        take("endcase")
        if position != len(records):
            problems.append(f"{len(records) - position} records after endcase")
    except (ValueError, IndexError) as error:
        problems.append(str(error))
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").strip().split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="dump in memory and compare with the file")
    parser.add_argument("--verify", action="store_true", help="re-read the file as FORMAT-specimen.md describes it")
    args = parser.parse_args(argv)
    path = OUT_DIR / f"{NAME}.golden"
    if args.verify:
        problems = verify(path.read_text(encoding="utf-8"))
        for problem in problems:
            print(f"{NAME}.golden: {problem}")
        print(f"{NAME}.golden: {'re-read, every stated sum holds' if not problems else 'DOES NOT VERIFY'}")
        return 1 if problems else 0
    w = dump()
    text = w.text()
    assert not verify(text), verify(text)
    # After the last import the dump makes and before the first byte is written.
    pinned_reference.require_all_modules()
    if args.check:
        same = path.is_file() and path.read_text(encoding="utf-8") == text
        print(f"{NAME}.golden: {w.cases} cases, {'identical' if same else 'DIFFERS from the file'}")
        return 0 if same else 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"{NAME}.golden: {w.cases} cases, {len(w.lines)} lines, {len(text.encode('utf-8'))} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
