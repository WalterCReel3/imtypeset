#!/usr/bin/env python3
"""
Dump where a block's material lands in what is shipped for it.

Writes tests/golden/para-map/map.golden: for a spread of plain-text blocks,
each set at several widths, the reference's answers to the three questions
`advtext.ui.units` asks before a copy --

  - `advtext.spans.map_text_block`: the shipped index of every node of the
    block's material, or none;
  - `advtext.ui.units._after_hard_breaks`: the index of the first item after
    each forced break;
  - `advtext.ui.units._originals_within`: what each replaced character was
    written as, by index.

The port derives all three from the breaker's own answer
(src/paragraph.h, `ParagraphLayout::shipped`); the reference recovers them by
matching the material against the shipped commands. The two must agree.

Every expectation is an answer of one of the reference's own functions,
called directly. `_after_hard_breaks` and `_originals_within` take a `Unit`
and read three of its fields (`blocks`, `cmds`, `spans`); they are handed an
object holding exactly those for the one block.

Records, over tools/oracle/FORMAT.md and FORMAT-para.md:

    case <name:string> map
    text <hard_breaks:bool> <text:string>     markdown.text_block's arguments
    block <align> <font:string> <left_indent> <first_line_indent> <marker_gap>
    spec baselineskip ... / spec lineskip ... / lineskiplimit <value>
    strut <height> <depth>
    marker <font:string> <text:string>        only with a list marker
    material <n>                              len(TextBlock.material)
    width <sp>                                then, once per width:
    shipped <n> <index or -1> ...             absolute, one per material node
    count <first> <items>                     SpanMap.base and SpanMap.count
    after_hard_breaks <n> <index> ...         as returned: may repeat an index
    originals <n> <index> <codepoint> ...     ascending by index
    endcase

The theme is `Theme.build(align=...)`: the default faces (prose, math, code),
`Spacing.EXTRA_SPACE_ONLY`, 96 px per inch, the paragraph or bullet-item
style. Nothing is recorded of the metrics: a port replays these with its own
font reader, which tests/golden/para already holds to the reference.

Run from the repository root:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=../imgui-adv-text \\
        ../imgui-adv-text/.venv/bin/python -B tools/oracle/dump_para_map.py

Two runs write identical bytes.
"""

from __future__ import annotations

import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Sequence

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))

import dump_core as core  # noqa: E402
from dump_core import emit_skip, q  # noqa: E402

from advtext import markdown, ui  # noqa: E402
from advtext.shipout import Point, ship  # noqa: E402
from advtext.spans import map_text_block  # noqa: E402
from advtext.style import (  # noqa: E402
    Align,
    BlockKind,
    Emphasis,
    Theme,
    char_measure,
    fontlib_metrics,
)
from advtext.ui import units  # noqa: E402
from advtext.units import Scaled, sp_from_px  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "tests" / "golden" / "para-map"
FORMAT_VERSION = 1
MEASURE = char_measure(fontlib_metrics)
ALIGNS = (Align.JUSTIFY, Align.LEFT, Align.RIGHT, Align.CENTER)
WIDTHS_PX = (40.0, 150.0, 400.0)

PROSE = (
    "The quick brown fox jumps over the lazy dog. Pack my box with five dozen "
    "liquor jugs! How vexingly quick daft zebras jump; AV To WA."
)
# U+4E00 and U+6F22 are in no face of the theme: each is set as U+FFFD.
STAND_INS = "one 一 two 漢一 three → four π r² end"
VERSE = "first line \nsecond  line\n\nafter a blank\n \nafter a blank of spaces\nlast"
BREAKS_ONLY = "a\n\n\nb"
STAND_INS_AND_BREAKS = "x 一\n漢 y\n\nz 一"
LONG_WORD = "a Pneumonoultramicroscopicsilicovolcanoconiosis b"


class Writer(core.Writer):
    def __init__(self, name: str, about: str) -> None:
        super().__init__(name, about)
        self.lines = [
            "# Generated by tools/oracle/dump_para_map.py from the Python reference. Do not edit.",
            "# Record vocabulary: the docstring of that script.",
            *[f"# {line}" for line in about.strip().splitlines()],
            f"golden {FORMAT_VERSION} {q('para-map/' + name)}",
        ]


def emit_case(
    w: Writer,
    name: str,
    text: str,
    align: Align,
    *,
    hard_breaks: bool = False,
    marker: str = "",
    indent: Scaled = 0,
    kind: BlockKind = BlockKind.PARAGRAPH,
    widths_px: Sequence[float] = WIDTHS_PX,
) -> None:
    theme = Theme.build(align=align)
    block = markdown.text_block(
        text, theme, fontlib_metrics, kind=kind, hard_breaks=hard_breaks, marker=marker, indent=indent
    )
    style = block.style
    w.case(name, "map")
    w.r("text", hard_breaks, q(text))
    w.r("block", style.align, q(style.font.key), block.left_indent, style.first_line_indent, theme.marker_gap)
    emit_skip(w, style.interline)
    w.r("strut", style.strut.height, style.strut.depth)
    if marker:
        w.r("marker", q(theme.font_for(kind, Emphasis()).key), q(marker))
    w.r("material", len(block.material))
    for px in widths_px:
        width = sp_from_px(px, theme.px_per_inch)
        vbox = ui.compose_blocks((block,), theme, width, MEASURE)
        cmds = ship(vbox, Point(0, vbox.height), measure=MEASURE)
        mapped = map_text_block(block, cmds)
        unit = SimpleNamespace(blocks=(block,), cmds=cmds, spans=((0, 0),))
        after = units._after_hard_breaks(unit, block, 0, 0)  # type: ignore[arg-type]
        originals = units._originals_within(unit)  # type: ignore[arg-type]
        w.r("width", width)
        w.r(
            "shipped",
            len(mapped.shipped),
            *[-1 if local is None else mapped.base + local for local in mapped.shipped],
        )
        w.r("count", mapped.base, mapped.count)
        w.r("after_hard_breaks", len(after), *after)
        flat: list[int] = []
        for index in sorted(originals):
            (character,) = originals[index]
            flat.extend((index, ord(character)))
        w.r("originals", len(originals), *flat)
    w.end()


def dump() -> Writer:
    w = Writer(
        "map",
        "advtext.spans.map_text_block, advtext.ui.units._after_hard_breaks and\n"
        "_originals_within for plain-text blocks, per alignment and width.",
    )
    theme = Theme.build()
    for align in ALIGNS:
        a = align.name.lower()
        emit_case(w, f"prose-{a}", PROSE, align)
        emit_case(w, f"stand-ins-{a}", STAND_INS, align)
        emit_case(w, f"verse-{a}", VERSE, align, hard_breaks=True)
        emit_case(w, f"breaks-only-{a}", BREAKS_ONLY, align, hard_breaks=True)
        emit_case(w, f"stand-ins-and-breaks-{a}", STAND_INS_AND_BREAKS, align, hard_breaks=True)
        emit_case(w, f"long-word-{a}", LONG_WORD, align)
        emit_case(w, f"empty-{a}", "", align)
        emit_case(
            w,
            f"bullet-{a}",
            PROSE,
            align,
            marker="•",
            indent=theme.list_indent,
            kind=BlockKind.BULLET_ITEM,
        )
        emit_case(
            w,
            f"ordered-verse-{a}",
            STAND_INS_AND_BREAKS,
            align,
            hard_breaks=True,
            marker="12.",
            indent=theme.list_indent,
            kind=BlockKind.ORDERED_ITEM,
        )
    return w


def main() -> int:
    writer = dump()
    data = writer.text().encode("utf-8")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "map.golden"
    path.write_bytes(data)
    print(f"{path.relative_to(ROOT)}: {writer.cases} cases, {len(writer.lines)} lines, {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
