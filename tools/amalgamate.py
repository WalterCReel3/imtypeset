#!/usr/bin/env python3
"""Writes the drop-in files: the library as a handful of files a host adds to
its own project next to Dear ImGui's, with no build system.

    python3 -I -B tools/amalgamate.py [--out DIR] [--check]

    --out DIR   where to write, default dist/ in this repository (git-ignored)
    --check     write nothing; exit 1 if DIR does not hold exactly what would
                be written (missing, stale or hand-edited files)

What is written, and from what:

    imtypeset.h         include/imtypeset.h, unchanged
    imtypeset.cpp       every src/*.cpp but the two below, and every private
                        header and .inc under src/, as one translation unit
    imtypeset_demo.cpp  src/imtypeset_demo.cpp: the demo window, optional
    imtypeset_c.h       include/imtypeset_c.h, unchanged: the C ABI, optional
    imtypeset_c.cpp     src/imtypeset_c.cpp, optional

src/ stays the source of truth: these files are an artefact, never edited and
never read back. The output depends on the inputs alone (no date, no host
name), so --check is a comparison of bytes.

How imtypeset.cpp is put together. The sources are taken in byte order of
their names. A line `#include "x"` naming a file under src/ is replaced by
that file the first time it is met and dropped afterwards; one naming a public
header or imgui.h is kept the first time and dropped afterwards; `#include
<...>` lines are left where they are; a header's `#pragma once` goes, since
there is no longer a header for it to guard. Nothing else is rewritten: no
symbol is renamed here, which is why the sources themselves must not define
the same name in two anonymous namespaces (the build compiles the result as a
test).

Standard library only. Run it with -I so that neither this directory nor the
current one is on sys.path.
"""

import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Translation units of their own in the drop-in set, as imgui_demo.cpp is: a
# host that does not want the demo window or the C ABI leaves the file out.
SEPARATE = ("imtypeset_demo.cpp", "imtypeset_c.cpp")

# Kept as includes: what the host has next to the drop-in files.
EXTERNAL = ("imgui.h", "imtypeset.h", "imtypeset_c.h")

INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*"([^"]+)"')
PRAGMA_ONCE = re.compile(r'^[ \t]*#[ \t]*pragma[ \t]+once[ \t]*$')
VERSION = re.compile(r'^#define[ \t]+IMTYPESET_VERSION[ \t]+"([^"]+)"', re.M)

GENERATED = """\
// GENERATED by tools/amalgamate.py from imtypeset {version}. Do not edit: change
// the sources and generate again.
"""

# Why the floating-point block is there: layout decisions turn on exact halves
# and the results are specified as IEEE double arithmetic evaluated one
# operation at a time. A compiler that fuses a*b+c into one FMA rounds once
# where that rounds twice, and one given -ffast-math may do anything. This file
# is compiled with the host's flags, so it asks for what it needs itself.
FLOATING_POINT = """\
//
// FLOATING POINT. The library's results are defined as IEEE double arithmetic
// with every operation rounded on its own: no fused multiply-add, no
// reassociation. Compile this file without -ffast-math, -Ofast,
// -funsafe-math-optimizations, -ffinite-math-only or /fp:fast. Contraction is
// switched off below for the compilers that have a way to say so in the
// source; passing -ffp-contract=off (GCC, Clang) or /fp:precise (MSVC) for
// this file does the same from the build and is the surer of the two. Fast-math
// is refused with an #error a little further down (src/units.h).
#if defined(__clang__)
#pragma STDC FP_CONTRACT OFF
#elif defined(__GNUC__)
// GCC ignores the STDC pragma; this is the form it honours.
#pragma GCC optimize("fp-contract=off")
#elif defined(_MSC_VER)
#pragma fp_contract(off)
#endif
"""


def read(path):
    with open(path, "r", encoding="utf-8", newline="") as handle:
        return handle.read()


def fail(message):
    sys.stderr.write("amalgamate.py: " + message + "\n")
    sys.exit(2)


class Amalgam:
    """One translation unit from the sources under src/."""

    def __init__(self, src):
        self.src = src
        self.seen = set()  # private files already expanded
        self.kept = set()  # external includes already emitted
        self.stack = []
        self.out = []

    def add(self, name):
        if name in self.stack:
            fail("include cycle: " + " -> ".join(self.stack + [name]))
        self.seen.add(name)
        self.stack.append(name)
        self.out.append("// ---- src/%s " % name + "-" * max(4, 84 - len(name)) + "\n")
        text = read(os.path.join(self.src, name))
        if not text.endswith("\n"):
            text += "\n"
        for line in text.splitlines(keepends=True):
            if PRAGMA_ONCE.match(line.rstrip("\r\n")):
                continue
            match = INCLUDE.match(line)
            if match is None:
                self.out.append(line)
                continue
            target = match.group(1)
            if target in EXTERNAL:
                if target not in self.kept:
                    self.kept.add(target)
                    self.out.append(line)
            elif os.path.isfile(os.path.join(self.src, target)):
                if target not in self.seen:
                    self.add(target)
                    self.out.append("// ---- src/%s, continued\n" % name)
            else:
                fail('src/%s includes "%s", which is neither under src/ nor one of %s'
                     % (name, target, ", ".join(EXTERNAL)))
        self.stack.pop()

    def text(self):
        return "".join(self.out)


def generate(repo, floating_point_guard=True):
    """The drop-in set as {file name: text}."""
    src = os.path.join(repo, "src")
    include = os.path.join(repo, "include")
    header = read(os.path.join(include, "imtypeset.h"))
    found = VERSION.search(header)
    if found is None:
        fail("include/imtypeset.h does not define IMTYPESET_VERSION")
    banner = GENERATED.format(version=found.group(1))

    names = sorted(os.listdir(src))  # byte order: the same on every machine
    sources = [n for n in names if n.endswith(".cpp") and n not in SEPARATE]
    private = [n for n in names if n.endswith((".h", ".inc"))]
    for name in SEPARATE:
        if name not in names:
            fail("src/%s is missing" % name)

    unit = Amalgam(src)
    for name in sources:
        unit.add(name)
    unused = [n for n in private if n not in unit.seen]
    if unused:
        # Nothing reaches it, so it would be left out without anyone noticing.
        fail("no source includes src/" + ", src/".join(unused))

    top = banner + "//\n// The whole library but the demo window and the C ABI:\n"
    line = "//  "
    for name in sources:
        if len(line) + len(name) + 1 > 79:
            top += line + "\n"
            line = "//  "
        line += " " + name
    top += line + "\n// and the private headers they include, each once.\n"
    if floating_point_guard:
        top += FLOATING_POINT
    top += "\n"

    files = {
        "imtypeset.h": header,
        "imtypeset_c.h": read(os.path.join(include, "imtypeset_c.h")),
        "imtypeset.cpp": top + unit.text(),
    }
    for name in SEPARATE:
        text = read(os.path.join(src, name))
        for line in text.splitlines():
            match = INCLUDE.match(line)
            if match is not None and match.group(1) not in EXTERNAL:
                fail('src/%s includes "%s": it has to build from the public headers alone'
                     % (name, match.group(1)))
        files[name] = banner + "// This is src/%s, unchanged below this notice.\n\n" % name + text
    return files


def main():
    parser = argparse.ArgumentParser(description="Write imtypeset's drop-in files.")
    parser.add_argument("--out", default=os.path.join(REPO, "dist"))
    parser.add_argument("--check", action="store_true")
    # For measuring what the block buys (docs/distribution.md): a file without
    # it, to compile with a compiler's default contraction.
    parser.add_argument("--no-floating-point-guard", action="store_true",
                        help="leave the contraction pragmas out")
    args = parser.parse_args()

    files = generate(REPO, not args.no_floating_point_guard)
    if args.check:
        stale = []
        for name, text in sorted(files.items()):
            path = os.path.join(args.out, name)
            if not os.path.isfile(path) or read(path) != text:
                stale.append(name)
        if stale:
            sys.stderr.write("amalgamate.py: %s is not what the sources give for: %s\n"
                             % (args.out, ", ".join(stale)))
            return 1
        print("amalgamate.py: %s is current (%d files)" % (args.out, len(files)))
        return 0

    os.makedirs(args.out, exist_ok=True)
    for name, text in sorted(files.items()):
        path = os.path.join(args.out, name)
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
    print("amalgamate.py: wrote %d files to %s (imtypeset.cpp: %d lines)"
          % (len(files), args.out, files["imtypeset.cpp"].count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
