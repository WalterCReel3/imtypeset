#!/usr/bin/env python3
"""
Generate src/mathtext_tables.inc from the reference's own tables.

The formula parser's vocabulary -- which command is which atom, which are
refused and with what words, what may follow \\left -- is data in
`advtext/mathtext.py`. This script imports that module and writes the tables it
holds as C++ arrays, so the port's tables are the reference's and not a
retyping of them. Run from the imtypeset repository root:

    PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=../imgui-adv-text \\
        ../imgui-adv-text/.venv/bin/python -B tools/gen_mathtext_tables.py

    ... gen_mathtext_tables.py --check   exit 1 if the file on disk is not what
                                         this would write

The script only reads the reference. Output is deterministic: every table is
sorted by its key, as bytes, which is the order the port's binary search needs.

What is generated is the *final* tables, after the reference has built them
(`_SYMBOLS`, `_UNICODE`), so the order in which the reference fills a
dictionary is not something the port has to reproduce.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from advtext import mathtext as T
from advtext.math.atoms import Atom, AtomType, Limits, MathChar, MuGlue, SubList

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "mathtext_tables.inc"


def c_string(text: str) -> str:
    """
    A C string literal for ASCII text. A character with no simple escape is
    written as a three-digit octal one, which cannot run into the character
    after it the way a hex escape can.
    """
    simple = {0x22: '\\"', 0x5C: "\\\\", 0x3F: "\\?"}
    out = ['"']
    for byte in text.encode("ascii"):
        if byte in simple:
            out.append(simple[byte])
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")
    out.append('"')
    return "".join(out)


def hexcp(codepoint: int) -> str:
    return f"0x{codepoint:04X}"


def atom_fields(atom: Atom) -> tuple[str, str, str, str]:
    """
    (kind, limits, codepoint, upright) for an atom of the symbol tables: one
    math character, or a run of upright ordinary characters (an operator name).
    """
    assert atom.sup is None and atom.sub is None
    kind = f"AtomType::{atom.kind.name}"
    limits = f"Limits::{atom.limits.name}"
    if isinstance(atom.nucleus, MathChar):
        return kind, limits, hexcp(atom.nucleus.codepoint), "nullptr"
    assert isinstance(atom.nucleus, SubList)
    letters = []
    for item in atom.nucleus.items:
        assert isinstance(item, Atom) and item.kind is AtomType.ORD
        assert item.sup is None and item.sub is None and item.limits is Limits.DEFAULT
        assert isinstance(item.nucleus, MathChar)
        letters.append(chr(item.nucleus.codepoint))
    return kind, limits, "0", c_string("".join(letters))


def generate() -> str:
    lines: list[str] = [
        "// Generated by tools/gen_mathtext_tables.py from the Python reference",
        "// (advtext/mathtext.py). Do not edit: change the reference, or the script.",
        "//",
        "// Every table is sorted by its key, as bytes. The entry types are declared",
        "// in src/mathtext.cpp, which is the only file that includes this one.",
        "",
        f"constexpr int TABLE_MAX_DEPTH = {T.MAX_DEPTH};",
        "",
    ]

    def table(decl: str, rows: list[str]) -> None:
        lines.append(f"constexpr {decl}[] = {{")
        lines.extend(f"    {row}," for row in rows)
        lines.append("};")
        lines.append("")

    # A command that is one atom, by name without the backslash.
    rows = []
    for name in sorted(T._SYMBOLS):
        kind, limits, codepoint, upright = atom_fields(T._SYMBOLS[name])
        rows.append(f"{{{c_string(name)}, {kind}, {limits}, {codepoint}, {upright}}}")
    table("SymbolEntry SYMBOLS", rows)

    # A character typed as itself: ASCII with TeX's math codes, then the
    # symbols a command already produces.
    for decl, source in (("CharacterEntry CHARACTERS", T._CHARACTERS), ("CharacterEntry UNICODE", T._UNICODE)):
        rows = []
        for character in sorted(source):
            assert len(character) == 1
            kind, limits, codepoint, upright = atom_fields(source[character])
            assert upright == "nullptr", character
            rows.append(f"{{{hexcp(ord(character))}, {kind}, {limits}, {codepoint}}}")
        table(decl, rows)

    rows = []
    for name in sorted(T._SPACES):
        atom = T._SPACES[name]
        assert atom.kind is AtomType.SPACE and isinstance(atom.nucleus, MuGlue)
        assert atom.sup is None and atom.sub is None and atom.limits is Limits.DEFAULT
        glue = atom.nucleus
        rows.append(f"{{{c_string(name)}, {glue.width}, {glue.stretch}, {glue.shrink}}}")
    table("SpaceEntry SPACES", rows)

    table(
        "ProseEntry PROSE",
        [f"{{{c_string(name)}, Face::{T._PROSE[name].name}}}" for name in sorted(T._PROSE)],
    )

    rows = []
    for character in sorted(T._DELIMITER_CHARACTERS):
        codepoint = T._DELIMITER_CHARACTERS[character]
        null = "true" if codepoint is None else "false"
        rows.append(f"{{{hexcp(ord(character))}, {hexcp(codepoint or 0)}, {null}}}")
    table("DelimiterCharacterEntry DELIMITER_CHARACTERS", rows)

    table(
        "DelimiterCommandEntry DELIMITER_COMMANDS",
        [f"{{{c_string(name)}, {hexcp(T._DELIMITER_COMMANDS[name])}}}" for name in sorted(T._DELIMITER_COMMANDS)],
    )

    rows = []
    for name in sorted(T._REFUSED):
        kind, reason = T._REFUSED[name]
        rows.append(f"{{{c_string(name)}, RefusalKind::{kind.name}, {c_string(reason)}}}")
    table("RefusedEntry REFUSED", rows)

    for decl, names in (
        ("const char* const MATRIX_ENVIRONMENTS", T._MATRIX_ENVIRONMENTS),
        ("const char* const TEXT_COMMANDS", T._TEXT_COMMANDS),
        ("const char* const ALPHABET_COMMANDS", T._ALPHABET_COMMANDS),
        ("const char* const SUPPORTED", T.supported_commands()),
    ):
        table(decl, [c_string(name) for name in sorted(names)])

    # What may follow \left and \right, as written.
    sized = T.sized_delimiters()
    rows = []
    for written in sorted(sized):
        codepoint = sized[written]
        rows.append(f"{{{c_string(written)}, {-1 if codepoint is None else hexcp(codepoint)}}}")
    table("SizedDelimiterEntry SIZED_DELIMITERS", rows)

    # Math italic: the ranges, and the letters whose italic form is elsewhere.
    table(
        "ItalicRange ITALIC_RANGES",
        [f"{{{hexcp(first)}, {hexcp(last)}, {hexcp(target)}}}" for first, last, target in sorted(T._ITALIC_RANGES)],
    )
    table(
        "CodepointPair ITALIC_EXCEPTIONS",
        [f"{{{hexcp(key)}, {hexcp(T._ITALIC_EXCEPTIONS[key])}}}" for key in sorted(T._ITALIC_EXCEPTIONS)],
    )
    # Letters the Letterlike Symbols block had filled before the mathematical
    # alphanumerics were encoded.
    for decl, holes in (("CodepointPair BLACKBOARD_HOLES", T._BLACKBOARD_HOLES), ("CodepointPair SCRIPT_HOLES", T._SCRIPT_HOLES)):
        table(decl, [f"{{{hexcp(ord(letter))}, {hexcp(holes[letter])}}}" for letter in sorted(holes)])

    # The script states these in code; assert the code has not moved from what
    # src/mathtext.cpp transcribes.
    assert T._alphabet("mathbb", "A") == 0x1D538 and T._alphabet("mathcal", "A") == 0x1D49C
    assert T._alphabet("mathbf", "A") == 0x1D400 and T._alphabet("mathbf", "a") == 0x1D41A
    assert T._alphabet("mathbf", "0") == 0x1D7CE and T._alphabet("mathbb", "a") is None
    assert T._SYMBOLS["prime"].nucleus == MathChar(0x2032)
    # The structures are parsed by name in src/mathtext.cpp; a new one in the
    # reference has to be written there, and this is where that is noticed.
    assert set(T._STRUCTURES) == {
        *("frac", "overline", "underline", "limits", "nolimits"),
        *("sqrt", "left", "right", "binom"),
    }, T._STRUCTURES
    assert T._TEXT_COMMANDS == ("mathrm", "operatorname")
    assert T._ALPHABET_COMMANDS == ("mathbb", "mathbf", "mathcal")
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").strip().splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the file on disk")
    args = parser.parse_args()
    text = generate()
    if args.check:
        on_disk = OUT.read_text(encoding="ascii") if OUT.exists() else ""
        if on_disk != text:
            print(f"{OUT.relative_to(ROOT)} is not what the reference's tables give", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)}: up to date")
        return 0
    OUT.write_text(text, encoding="ascii")
    print(f"{OUT.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
